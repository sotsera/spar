namespace Spar.PackageTests;

/// <summary>
/// A contract library that reaches the app as a NuGet package (decision "Contracts from referenced libraries: the app
/// opts in"): the library is packed from its own folder with the <c>Spar</c> package alone, and the app that lists it
/// serves its interface contract with its own implementation, through the generated dispatch, test client and
/// TypeScript module, whose comments come from the documentation file in the package.
/// </summary>
public sealed class LibraryPackageTests(Consumer consumer) : IDisposable
{
    [Fact]
    public async Task An_app_serves_the_contract_of_a_library_it_gets_as_a_package()
    {
        var project = $"{LibraryConsumerFiles.PackageId}.csproj";
        var (packed, packOutput) = await consumer.DotnetInAsync(consumer.LibraryRoot, "", "pack", project, "-c", "Release",
            $"-p:Version={consumer.LibraryVersion}", "-o", consumer.LibraryFeed, "-nologo");
        Assert.True(packed == 0, packOutput);

        var (exit, output) = await consumer.DotnetInAsync(consumer.LibraryAppRoot, "", "test", "--project",
            Path.Combine("App.Tests", "Notes.App.Tests.csproj"));

        Assert.True(exit == 0, output);
        Assert.Contains("succeeded: 2", output, StringComparison.Ordinal);
        var app = Path.Combine(consumer.LibraryAppRoot, "App");
        var snapshot = File.ReadAllText(Path.Combine(app, "Notes.App.contracts.snapshot"));
        Assert.Contains("contract tags (Notes.Tags.ITagsService)\n  add(string) -> Notes.Tags.Tag | Notes.Tags.TagError\n", snapshot, StringComparison.Ordinal);
        var module = File.ReadAllText(Path.Combine(app, "obj", "spar", "client", "tags.d.ts"));
        Assert.StartsWith($"// Generated by Spar from {LibraryConsumerFiles.PackageId} (a referenced library).", module, StringComparison.Ordinal);
        string[] comments =
        [
            "/** Tags for notes, shared between apps. Each app implements it. Wire name: tags. */",
            "  /** Adds `name` and returns it with its count, or why it was refused. */\n  readonly add:",
            "  /** How many times it was added, in any letter case. */\n  readonly count: number;",
        ];
        Assert.All(comments, comment => Assert.Contains(comment, module, StringComparison.Ordinal));
    }

    public void Dispose() => consumer.Report(TestContext.Current.TestState?.Result == TestResult.Passed);
}
