namespace Spar.Sdk.Tasks.Tests;

/// <summary>What the client step writes: the package layout, the declarations and the modules.</summary>
public sealed class EmitterTests
{
    [Fact]
    public void The_package_has_a_module_per_contract_shared_types_and_the_fingerprint()
    {
        var files = ClientHarness.Emit(Fixtures.Shop);

        Assert.Equal(
            ["orders.d.ts", "orders.d.ts.map", "orders.js", "package.json", "shared.d.ts", "shared.d.ts.map", "shared.js", "spar.d.ts", "spar.js", "stock.d.ts", "stock.d.ts.map", "stock.js"],
            files.Keys);
        Assert.Contains("\"./orders\": {\n      \"types\": \"./orders.d.ts\",\n      \"default\": \"./orders.js\"\n    }", files["package.json"], StringComparison.Ordinal);
        Assert.Contains("\"version\": \"1.2.3\"", files["package.json"], StringComparison.Ordinal);
        Assert.DoesNotContain("\"./shared\"", files["package.json"], StringComparison.Ordinal);
        Assert.Matches("export const fingerprint = \"[0-9a-f]{16}\";", files["spar.js"]);
    }

    [Fact]
    public void A_contract_declares_its_own_types_and_re_exports_the_shared_ones()
    {
        var orders = ClientHarness.Emit(Fixtures.Shop)["orders.d.ts"];

        Assert.StartsWith("// Generated by Spar from Contracts.cs. Do not edit.\nimport type { Call, CallOptions } from \"@spar/app/sdk\";\n", orders, StringComparison.Ordinal);
        Assert.Contains("import type { Item } from \"./shared.js\";\n\nexport type { Item } from \"./shared.js\";\n", orders, StringComparison.Ordinal);
        Assert.Contains("export interface Basket {\n  readonly items: readonly Item[];\n  readonly coupon: number | null;\n  readonly notes: readonly (string | null)[];\n}\n", orders, StringComparison.Ordinal);
        Assert.Contains("export interface Receipt {\n  readonly id: string;\n  readonly at: string;\n  readonly paid: boolean;\n}\n", orders, StringComparison.Ordinal);
        Assert.DoesNotContain("interface Item", orders, StringComparison.Ordinal);
    }

    [Fact]
    public void Every_return_shape_has_its_call_type()
    {
        var orders = ClientHarness.Emit(Fixtures.Shop)["orders.d.ts"];

        Assert.Contains("  /** Places an order for the `Basket`. */\n  readonly place: (request: Basket, options?: CallOptions) => Call<Receipt, OrderError>;\n", orders, StringComparison.Ordinal);
        Assert.Contains("  readonly cancel: (orderId: string, options?: CallOptions) => Call<void, OrderError>;\n", orders, StringComparison.Ordinal);
        Assert.Contains("  readonly clear: (options?: CallOptions) => Call<void>;\n", orders, StringComparison.Ordinal);
        Assert.Contains("  readonly count: (options?: CallOptions) => Call<bigint>;\n", orders, StringComparison.Ordinal);
        Assert.Contains("/** Takes orders. Wire name: orders. */\nexport declare const orders: {\n", orders, StringComparison.Ordinal);
    }

    [Fact]
    public void Errors_are_an_interface_map_with_their_documentation()
    {
        var orders = ClientHarness.Emit(Fixtures.Shop)["orders.d.ts"];

        var expected = """
            /** Why an order failed; never ends this comment early: *\/ (C# `OrderError`) */
            export interface OrderError {
              /** The item is gone. */
              readonly outOfStock: {
                readonly sku: string;
                readonly left: bigint;
              };

              readonly closed: undefined;
            }

            """.Replace("\r\n", "\n", StringComparison.Ordinal);
        Assert.Contains(expected, orders, StringComparison.Ordinal);
    }

    [Fact]
    public void Shared_types_carry_their_documentation()
    {
        var shared = ClientHarness.Emit(Fixtures.Shop)["shared.d.ts"];

        Assert.Contains("/** An item in the catalogue. */\nexport interface Item {\n  /** The stock-keeping unit, for example `A-100`. */\n  readonly sku: string;\n  readonly stock: bigint;\n", shared, StringComparison.Ordinal);
        Assert.Contains("  readonly replacement: Item | null;\n", shared, StringComparison.Ordinal);
    }

    [Fact]
    public void Modules_read_and_write_field_by_field_and_hand_invoke_the_encoder()
    {
        var files = ClientHarness.Emit(Fixtures.Shop);

        Assert.Contains("import { readItem, writeItem } from \"./shared.js\";\n", files["orders.js"], StringComparison.Ordinal);
        Assert.Contains("    items: wire.readList(wire.field(object, \"items\"), readItem),\n", files["orders.js"], StringComparison.Ordinal);
        Assert.Contains("    wire.member(\"notes\", wire.writeList(value.notes, item => wire.writeNullable(item, wire.writeString))),\n", files["orders.js"], StringComparison.Ordinal);
        Assert.Contains("  cancel: (orderId, options) => invoke(\"orders\", \"cancel\", () => wire.writeString(orderId), decodeCancel, options),\n", files["orders.js"], StringComparison.Ordinal);
        Assert.Contains("  clear: options => invoke(\"orders\", \"clear\", () => \"\", decodeClear, options),\n", files["orders.js"], StringComparison.Ordinal);
        Assert.Contains("const decodeList = { value: json => wire.readList(JSON.parse(json), readItem), error: noErrors };\n", files["stock.js"], StringComparison.Ordinal);
        Assert.Contains("export function readItem(value) {\n", files["shared.js"], StringComparison.Ordinal);
        Assert.DoesNotContain("Object.assign", string.Concat(files.Values), StringComparison.Ordinal);
        Assert.DoesNotContain("...", string.Concat(files.Values), StringComparison.Ordinal);
    }

    [Fact]
    public void Error_cases_are_read_by_a_switch_with_a_block_each()
    {
        var orders = ClientHarness.Emit(Fixtures.Shop)["orders.js"];

        var expected = """
            function readOrderError(code, payload) {
              switch (code) {
                case "outOfStock": {
                  const object = payload;
                  return {
                    sku: wire.readString(wire.field(object, "sku")),
                    left: wire.readInt64(wire.field(object, "left")),
                  };
                }
                case "closed":
                  return undefined;
                default:
                  return unknownErrorCase;
              }
            }

            """.Replace("\r\n", "\n", StringComparison.Ordinal);
        Assert.Contains(expected, orders, StringComparison.Ordinal);
    }

    [Fact]
    public void A_type_in_the_global_namespace_keeps_its_plain_name()
    {
        const string Source = """
            using System.Threading.Tasks;
            using Spar;

            public sealed record Note(string Text);

            [SparContract]
            public sealed class NotesService
            {
                [SparCommand]
                public Task<Note> ReadAsync(string id) => throw new System.NotImplementedException();
            }
            """;

        var notes = ClientHarness.Emit(Source)["notes.d.ts"];

        Assert.Contains("export interface Note {\n", notes, StringComparison.Ordinal);
        Assert.Contains("readonly read: (id: string, options?: CallOptions) => Call<Note>;", notes, StringComparison.Ordinal);
        Assert.DoesNotContain("global::", notes, StringComparison.Ordinal);
    }

    [Fact]
    public void Generated_text_uses_LF_only()
    {
        var files = ClientHarness.Emit(Fixtures.Shop);

        Assert.All(files.Values, text => Assert.DoesNotContain('\r', text));
    }
}
