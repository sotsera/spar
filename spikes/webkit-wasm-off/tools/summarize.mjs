// Summarises results/runs/*.json into results/summary.md (one row per run and realm).
// Usage, from the spike folder: node tools/summarize.mjs [results folder, default results]
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const base = process.argv[2] ?? "results";
const runsDir = join(base, "runs");
const steps = ["validate", "compile", "moduleSync", "instanceSync", "instantiateBytes", "instantiateModule", "compileStreaming", "instantiateStreaming", "memory"];

const cell = (r) => {
  if (!r) return "–";
  if (r.ok && typeof r.value === "string" && r.value.startsWith("compile failed first")) return "compile blocked first";
  if (r.ok) return r.value === true ? "ok" : `ok ${JSON.stringify(r.value)}`;
  const e = String(r.error);
  if (e.includes("Refused to create a WebAssembly object")) return "CSP CompileError";
  if (e.includes("Refused to evaluate")) return "CSP EvalError";
  return e.split("\n")[0].slice(0, 60);
};
const suiteRow = (label, realm, s) => {
  if (!s) return `| ${label} | ${realm} | (no result) |${" |".repeat(steps.length)}`;
  return `| ${label} | ${realm} | ${s.typeofWebAssembly} | ${steps.map((k) => cell(s[k])).join(" | ")} |`;
};

const lines = [
  "# Run summary (generated by tools/summarize.mjs)",
  "",
  "`–` = not run in that realm. `CSP CompileError` = \"Refused to create a WebAssembly object because 'unsafe-eval' or 'wasm-unsafe-eval' is not an allowed source of script…\".",
  "",
  `| run | realm | typeof WebAssembly | ${steps.join(" | ")} |`,
  `|---|---|---|${steps.map(() => "---").join("|")}|`,
];
const extra = ["", "## Per run", ""];
for (const file of readdirSync(runsDir).filter((f) => f.endsWith(".json")).sort()) {
  const d = JSON.parse(readFileSync(join(runsDir, file), "utf8"));
  const r = d.report;
  const label = d.label;
  if (!r) {
    lines.push(`| ${label} | (no report) |`);
    continue;
  }
  lines.push(suiteRow(label, "page", r.main));
  lines.push(suiteRow(label, "worker, CSP header", r.workerWithCsp?.data?.suite));
  lines.push(suiteRow(label, "worker, no CSP header", r.workerWithoutCsp?.data?.suite));
  for (const [k, f] of Object.entries(r.frames || {})) lines.push(suiteRow(label, `iframe ${k} (${f.url ?? f.access})`, f.suite));
  const pm = r.postedModule || {};
  const env = d.webkitProcesses.map((p) => `${p.process}: ${p.environError ?? (p.jscEnv.join(" ") || "no JSC_")}`).join("; ");
  extra.push(
    `- **${label}**: profile \`${d.profile}\`, origin ${d.origin}, user script ${d.userScript}, extension ${d.extension ?? "none"}, setenv [${d.setenv.join(" ")}], jsc-ui [${d.jscUi.join(" ")}].` +
      ` initial typeof ${r.initial?.typeofWebAssembly}; eval ${cell(r.evalChecks?.eval)}; ESM import ${cell(r.esmImportWasm)};` +
      ` posted Module → worker with CSP: ${pm.compileInPage ? "page compile failed: " + pm.compileInPage.slice(0, 50) : cell(pm.toWorkerWithCsp?.data?.instantiatePostedModule)}, without CSP: ${cell(pm.toWorkerWithoutCsp?.data?.instantiatePostedModule)};` +
      ` blob worker ${r.blobWorker?.value?.event ?? cell(r.blobWorker)}; recovery ${JSON.stringify(Object.fromEntries(Object.entries(r.recovery || {}).map(([k, v]) => [k, v.ok ? v.value : v.error])))};` +
      ` violations ${r.violations.map((v) => `${v.directive}:${v.blocked}`).join(",") || "none"}; jsWork ms ${r.jsWork.map((w) => w.ms).join("/")}; report at ${d.hostMs.reportAt} ms after host start; web processes: ${env}.`,
  );
}
writeFileSync(join(base, "summary.md"), lines.concat(extra).join("\n") + "\n");
console.log(lines.concat(extra).join("\n"));
