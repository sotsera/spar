using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Spike.Generator;

public enum SerializerMode
{
    /// <summary>Generated <c>Utf8JsonReader</c>/<c>Utf8JsonWriter</c> code; no System.Text.Json metadata.</summary>
    Spar,

    /// <summary>System.Text.Json source-generated metadata from an application-authored context (size baseline).</summary>
    Stj,
}

/// <summary>Emits the C# dispatch, serializers and catalog for a set of contracts.</summary>
public static class CSharpEmitter
{
    private const string Header = "// <auto-generated/>\n#nullable enable\n";

    public static string EmitBinding(ContractModel contract, SerializerMode mode)
    {
        var sb = new StringBuilder(Header);
        sb.AppendLine("using global::System.Text.Json;");
        sb.AppendLine();
        sb.AppendLine("namespace Spar.Generated;");
        sb.AppendLine();
        sb.AppendLine($"internal static class {contract.TypeName}Binding");
        sb.AppendLine("{");
        sb.AppendLine($"    public static global::System.Threading.Tasks.ValueTask<byte[]> InvokeAsync({contract.CSharp} service, string command, global::System.ReadOnlyMemory<byte> payload, global::System.Threading.CancellationToken cancellationToken) => command switch");
        sb.AppendLine("    {");
        foreach (var command in contract.Commands.Where(c => c.Kind == CommandKind.Unary))
        {
            sb.AppendLine($"        \"{command.WireName}\" => {command.MethodName}(service, payload, cancellationToken),");
        }

        sb.AppendLine($"        _ => throw new global::Spike.SparUnknownCommandException($\"Unknown command '{{command}}' on contract '{contract.WireName}'.\"),");
        sb.AppendLine("    };");

        // Streams and subscriptions: the host pulls the returned SparStream in batches.
        var streams = mode == SerializerMode.Spar ? contract.Commands.Where(c => c.Kind != CommandKind.Unary).ToList() : [];
        sb.Append('\n');
        sb.Append($"    public static global::Spike.SparStream OpenStream({contract.CSharp} service, string command, global::System.ReadOnlyMemory<byte> payload, global::System.Threading.CancellationToken cancellationToken) => command switch\n");
        sb.Append("    {\n");
        foreach (var command in streams)
        {
            sb.Append($"        \"{command.WireName}\" => Open{command.MethodName}(service, payload, cancellationToken),\n");
        }

        sb.Append($"        _ => throw new global::Spike.SparUnknownCommandException($\"Unknown stream '{{command}}' on contract '{contract.WireName}'.\"),\n");
        sb.Append("    };\n");
        foreach (var command in streams)
        {
            var arguments = new List<string>();
            sb.Append('\n');
            sb.Append($"    private static global::Spike.SparStream Open{command.MethodName}({contract.CSharp} service, global::System.ReadOnlyMemory<byte> payload, global::System.Threading.CancellationToken cancellationToken)\n");
            sb.Append("    {\n");
            if (command.Request is not null)
            {
                sb.Append($"        var request = {ReadPayload(command, mode)};\n");
                arguments.Add("request");
            }

            if (command.TakesCancellation)
            {
                arguments.Add("cancellationToken");
            }

            var source = $"service.{command.MethodName}({string.Join(", ", arguments)})";
            var write = $"static (writer, v) => {{ {WriteValue(command.Response, "v", 0)} }}";
            sb.Append(command.Kind == CommandKind.Subscription
                ? $"        return global::Spike.SparStream.Subscribe<{Declared(command.Response)}>({source}, {write}, {command.Capacity}, cancellationToken);\n"
                : $"        return global::Spike.SparStream.Create<{Declared(command.Response)}>({source}, {write}, cancellationToken);\n");
            sb.Append("    }\n");
            EmitParse(sb, command, mode);
        }

        foreach (var command in contract.Commands.Where(c => c.Kind == CommandKind.Unary))
        {
            sb.AppendLine();
            sb.AppendLine($"    private static async global::System.Threading.Tasks.ValueTask<byte[]> {command.MethodName}({contract.CSharp} service, global::System.ReadOnlyMemory<byte> payload, global::System.Threading.CancellationToken cancellationToken)");
            sb.AppendLine("    {");
            var arguments = new List<string>();
            if (command.Request is { } request)
            {
                sb.AppendLine($"        var request = {ReadPayload(command, mode)};");
                arguments.Add("request");
            }

            if (command.TakesCancellation)
            {
                arguments.Add("cancellationToken");
            }

            sb.AppendLine($"        var result = await service.{command.MethodName}({string.Join(", ", arguments)}).ConfigureAwait(false);");
            sb.AppendLine($"        return {WritePayload(command.Response, "result", mode)};");
            sb.AppendLine("    }");

            EmitParse(sb, command, mode);
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void EmitParse(StringBuilder sb, CommandModel command, SerializerMode mode)
    {
        if (command.Request is not { } parsed || mode != SerializerMode.Spar)
        {
            return;
        }

        // A request that does not parse never reaches the service: report it as "not executed".
        sb.Append('\n');
        sb.Append($"    private static {Declared(parsed)} Parse{command.MethodName}(global::System.ReadOnlyMemory<byte> payload)\n");
        sb.Append("    {\n");
        sb.Append("        try\n");
        sb.Append("        {\n");
        sb.Append("            var reader = global::Spike.SparJson.Begin(payload.Span);\n");
        sb.Append($"            return {ReadValue(parsed, "reader")};\n");
        sb.Append("        }\n");
        sb.Append("        catch (global::System.Text.Json.JsonException exception)\n");
        sb.Append("        {\n");
        sb.Append("            throw new global::Spike.SparInvalidRequestException(exception.Message, exception);\n");
        sb.Append("        }\n");
        sb.Append("    }\n");
    }

    public static string EmitCatalog(IReadOnlyList<ContractModel> contracts, string manifestJson)
    {
        var sb = new StringBuilder(Header);
        sb.AppendLine("namespace Spar.Generated;");
        sb.AppendLine();
        sb.AppendLine("internal static class SparCatalog");
        sb.AppendLine("{");
        sb.AppendLine($"    public const string Manifest = {Literal(manifestJson)};");
        sb.AppendLine();
        sb.AppendLine("    public static global::System.Threading.Tasks.ValueTask<byte[]> InvokeAsync(global::System.Func<global::System.Type, object> resolve, string contract, string command, global::System.ReadOnlyMemory<byte> payload, global::System.Threading.CancellationToken cancellationToken) => contract switch");
        sb.AppendLine("    {");
        foreach (var contract in contracts)
        {
            sb.AppendLine($"        \"{contract.WireName}\" => {contract.TypeName}Binding.InvokeAsync(({contract.CSharp})resolve(typeof({contract.CSharp})), command, payload, cancellationToken),");
        }

        sb.AppendLine("        _ => throw new global::Spike.SparUnknownCommandException($\"Unknown contract '{contract}'.\"),");
        sb.AppendLine("    };");
        sb.Append('\n');
        sb.Append("    public static global::Spike.SparStream OpenStream(global::System.Func<global::System.Type, object> resolve, string contract, string command, global::System.ReadOnlyMemory<byte> payload, global::System.Threading.CancellationToken cancellationToken) => contract switch\n");
        sb.Append("    {\n");
        foreach (var contract in contracts)
        {
            sb.Append($"        \"{contract.WireName}\" => {contract.TypeName}Binding.OpenStream(({contract.CSharp})resolve(typeof({contract.CSharp})), command, payload, cancellationToken),\n");
        }

        sb.Append("        _ => throw new global::Spike.SparUnknownCommandException($\"Unknown contract '{contract}'.\"),\n");
        sb.Append("    };\n");
        sb.AppendLine("}");
        return sb.ToString();
    }

    public static string EmitSerializers(IEnumerable<DtoModel> dtos)
    {
        var sb = new StringBuilder(Header);
        sb.AppendLine("using global::System.Text.Json;");
        sb.AppendLine();
        sb.AppendLine("namespace Spar.Generated;");
        sb.AppendLine();
        sb.AppendLine("internal static class SparSerializers");
        sb.AppendLine("{");
        foreach (var dto in dtos)
        {
            EmitReader(sb, dto);
            EmitWriter(sb, dto);
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void EmitReader(StringBuilder sb, DtoModel dto)
    {
        sb.AppendLine($"    public static {dto.CSharp} Read{dto.Name}(ref Utf8JsonReader reader)");
        sb.AppendLine("    {");
        sb.AppendLine("        if (reader.TokenType != JsonTokenType.StartObject)");
        sb.AppendLine("        {");
        sb.AppendLine($"            throw new JsonException($\"Expected an object for {dto.Name} but found {{reader.TokenType}}.\");");
        sb.AppendLine("        }");
        sb.AppendLine();
        var index = 0;
        foreach (var property in dto.Properties)
        {
            sb.AppendLine($"        {Local(property.Type)} p{index} = default;");
            if (!property.Type.Nullable)
            {
                sb.AppendLine($"        var has{index} = false;");
            }
            index++;
        }

        sb.AppendLine("        while (reader.Read() && reader.TokenType != JsonTokenType.EndObject)");
        sb.AppendLine("        {");
        index = 0;
        foreach (var property in dto.Properties)
        {
            var keyword = index == 0 ? "if" : "else if";
            sb.AppendLine($"            {keyword} (reader.ValueTextEquals(\"{property.JsonName}\"u8))");
            sb.AppendLine("            {");
            sb.AppendLine("                reader.Read();");
            sb.AppendLine($"                p{index} = {ReadValue(property.Type, "reader")};");
            if (!property.Type.Nullable)
            {
                sb.AppendLine($"                has{index} = true;");
            }
            sb.AppendLine("            }");
            index++;
        }

        sb.AppendLine("            else");
        sb.AppendLine("            {");
        sb.AppendLine("                reader.Read();");
        sb.AppendLine("                reader.Skip();");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
        sb.AppendLine();
        index = 0;
        var arguments = new List<string>();
        foreach (var property in dto.Properties)
        {
            if (!property.Type.Nullable)
            {
                sb.AppendLine($"        if (!has{index}) throw new JsonException(\"{dto.Name} requires '{property.JsonName}'.\");");
                arguments.Add(IsValueType(property.Type) ? $"p{index}" : $"p{index}!");
            }
            else
            {
                arguments.Add($"p{index}");
            }

            index++;
        }

        sb.AppendLine($"        return new {dto.CSharp}({string.Join(", ", arguments)});");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitWriter(StringBuilder sb, DtoModel dto)
    {
        sb.AppendLine($"    public static void Write{dto.Name}(Utf8JsonWriter writer, {dto.CSharp} value)");
        sb.AppendLine("    {");
        sb.AppendLine("        writer.WriteStartObject();");
        foreach (var property in dto.Properties)
        {
            sb.AppendLine($"        writer.WritePropertyName(\"{property.JsonName}\"u8);");
            sb.AppendLine($"        {WriteValue(property.Type, $"value.{property.Name}", 2)}");
        }

        sb.AppendLine("        writer.WriteEndObject();");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static string ReadValue(TypeRef type, string reader)
    {
        var read = type.Kind switch
        {
            WireKind.String => $"global::Spike.SparJson.ReadString(ref {reader})",
            WireKind.Int32 => $"{reader}.GetInt32()",
            WireKind.Int64 => $"{reader}.GetInt64()",
            WireKind.Double => $"{reader}.GetDouble()",
            WireKind.Boolean => $"{reader}.GetBoolean()",
            WireKind.Array => $"global::Spike.SparJson.ReadArray<{Declared(type.Element!)}>(ref {reader}, static (ref Utf8JsonReader r) => {ReadValue(type.Element!, "r")})",
            WireKind.Dto => $"global::Spar.Generated.SparSerializers.Read{ShortName(type)}(ref {reader})",
            _ => throw new System.InvalidOperationException(type.Kind.ToString()),
        };

        return type.Nullable ? $"{reader}.TokenType == JsonTokenType.Null ? null : {read}" : read;
    }

    private static string WriteValue(TypeRef type, string value, int depth)
    {
        var write = type.Kind switch
        {
            WireKind.String => $"writer.WriteStringValue({value});",
            WireKind.Int32 or WireKind.Int64 or WireKind.Double => $"writer.WriteNumberValue({ValueOf(type, value)});",
            WireKind.Boolean => $"writer.WriteBooleanValue({ValueOf(type, value)});",
            WireKind.Array => $"writer.WriteStartArray(); foreach (var e{depth} in {value}) {{ {WriteValue(type.Element!, $"e{depth}", depth + 1)} }} writer.WriteEndArray();",
            WireKind.Dto => $"global::Spar.Generated.SparSerializers.Write{ShortName(type)}(writer, {value});",
            _ => throw new System.InvalidOperationException(type.Kind.ToString()),
        };

        return type.Nullable ? $"if ({value} is null) {{ writer.WriteNullValue(); }} else {{ {write} }}" : write;
    }

    private static string ValueOf(TypeRef type, string value) => type.Nullable ? $"{value}.Value" : value;

    private static string ReadPayload(CommandModel command, SerializerMode mode) => mode == SerializerMode.Stj
        ? $"global::System.Text.Json.JsonSerializer.Deserialize(payload.Span, global::Spike.App.SpikeJsonContext.Default.{StjName(command.Request!)})!"
        : $"Parse{command.MethodName}(payload)";

    private static string WritePayload(TypeRef type, string value, SerializerMode mode) => mode == SerializerMode.Stj
        ? $"global::System.Text.Json.JsonSerializer.SerializeToUtf8Bytes({value}, global::Spike.App.SpikeJsonContext.Default.{StjName(type)})"
        : $"global::Spike.SparJson.Write({value}, static (writer, v) => {{ {WriteValue(type, "v", 0)} }})";

    private static string StjName(TypeRef type) => type.Kind switch
    {
        WireKind.Array => StjName(type.Element!) + "Array",
        WireKind.Dto => ShortName(type),
        WireKind.String => "String",
        WireKind.Int32 => "Int32",
        WireKind.Int64 => "Int64",
        WireKind.Double => "Double",
        WireKind.Boolean => "Boolean",
        _ => throw new System.InvalidOperationException(type.Kind.ToString()),
    };

    private static string ShortName(TypeRef type) => type.DtoName!.Substring(type.DtoName.LastIndexOf('.') + 1);

    private static string Declared(TypeRef type) => type.Kind == WireKind.Array
        ? $"{Declared(type.Element!)}[]{(type.Nullable ? "?" : string.Empty)}"
        : type.CSharp + (type.Nullable ? "?" : string.Empty);

    private static string Local(TypeRef type)
    {
        var declared = Declared(type);
        return IsValueType(type) || declared.EndsWith("?", System.StringComparison.Ordinal) ? declared : declared + "?";
    }

    private static bool IsValueType(TypeRef type) =>
        type.Kind is WireKind.Int32 or WireKind.Int64 or WireKind.Double or WireKind.Boolean;

    private static string Literal(string value) => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
}
