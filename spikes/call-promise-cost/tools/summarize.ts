// Reads results/raw/<engine>-<run>.json and writes results/summary.md (all engines) plus a console copy.
// Usage: node tools/summarize.ts [rawDir] [outFile]
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const spike = join(dirname(fileURLToPath(import.meta.url)), "..");
const rawDir = process.argv[2] ?? join(spike, "results", "raw");
const outFile = process.argv[3] ?? join(spike, "results", "summary.md");

type Json = any; // eslint-disable-line @typescript-eslint/no-explicit-any
const ROUND_TRIP_US = [59, 79];
const variants = ["native", "formC", "subclass", "of", "noSpecies", "ctor"];
const labels: Record<string, string> = {
  native: "native Promise (baseline)",
  formC: "form C thenable (today)",
  subclass: "Promise subclass, direct (proposal)",
  of: "Promise subclass via `of`",
  noSpecies: "Promise subclass, no species",
  ctor: "Promise subclass, `constructor === Promise` (exploratory)",
};
const styles = ["await", "match", "unwrap"];
const styleLabel: Record<string, string> = { await: "`(await call).match(h)`", match: "`await call.match(h)`", unwrap: "`await call.unwrap()`" };

const median = (values: number[]): number => {
  const s = [...values].sort((a, b) => a - b);
  const m = s.length >> 1;
  return s.length % 2 ? s[m]! : (s[m - 1]! + s[m]!) / 2;
};
const f0 = (x: number) => x.toFixed(0);
const f1 = (x: number) => x.toFixed(1);
const f2 = (x: number) => x.toFixed(2);

const byEngine = new Map<string, { file: string; report: Json }[]>();
for (const file of readdirSync(rawDir).filter(f => f.endsWith(".json") && !f.startsWith("probe-")).sort()) {
  const report = JSON.parse(readFileSync(join(rawDir, file), "utf8"));
  if (report.error) { console.error(`${file}: page error ${report.error}`); continue; }
  const engine = file.replace(/-\d+\.json$/, "");
  (byEngine.get(engine) ?? byEngine.set(engine, []).get(engine)!).push({ file, report });
}

const out: string[] = [];
const line = (s = "") => out.push(s);

line("# call-promise-cost: summary");
line();
line(`Generated by \`tools/summarize.ts\` from \`results/raw/\`. Times are ns per call; "runs" are separate processes or page loads.`);

for (const [engine, runs] of byEngine) {
  const first = runs[0]!.report;
  line();
  line(`## ${engine}`);
  line();
  line(`Runs: ${runs.length} (${runs.map(r => r.file).join(", ")}). Calls per timed sample: ${runs.map(r => r.report.timing.callsPerSample).join(", ")}; ` +
    `${first.options.rounds} measured rounds after ${first.options.warmupRounds} warm-up rounds per run.`);
  line();
  line("Details: `" + JSON.stringify(first.details) + "`");

  // Time per call.
  line();
  line("### Time per call (create, settle, consume)");
  line();
  line("Median of the per-run medians, then the range of per-run medians in brackets, then the change against the native baseline for the same style.");
  line();
  line(`| Variant | ${styles.map(s => styleLabel[s]).join(" | ")} |`);
  line(`|---|${styles.map(() => "---:").join("|")}|`);
  const med: Record<string, number> = {};
  for (const v of variants) {
    for (const s of styles) {
      const perRun = runs.map(r => median(r.report.timing.samples[`${v}.${s}`]));
      med[`${v}.${s}`] = median(perRun);
    }
  }

  for (const v of variants) {
    const cells = styles.map(s => {
      const perRun = runs.map(r => median(r.report.timing.samples[`${v}.${s}`]));
      const m = med[`${v}.${s}`]!;
      const delta = m - med[`native.${s}`]!;
      return `${f0(m)} [${f0(Math.min(...perRun))}–${f0(Math.max(...perRun))}]${v === "native" ? "" : ` (${delta >= 0 ? "+" : ""}${f0(delta)})`}`;
    });
    line(`| ${labels[v]} | ${cells.join(" | ")} |`);
  }

  line();
  line("Within-run spread (min–max of all measured samples, all runs):");
  line();
  line(`| Variant | ${styles.join(" | ")} |`);
  line(`|---|${styles.map(() => "---:").join("|")}|`);
  for (const v of variants) {
    line(`| ${labels[v]} | ${styles.map(s => { const all = runs.flatMap(r => r.report.timing.samples[`${v}.${s}`] as number[]); return `${f0(Math.min(...all))}–${f0(Math.max(...all))}`; }).join(" | ")} |`);
  }

  line();
  const worst = Math.max(...styles.map(s => med[`subclass.${s}`]! - med[`native.${s}`]!));
  const worstC = Math.max(...styles.map(s => med[`subclass.${s}`]! - med[`formC.${s}`]!));
  line(`Proposal against the bridge round trip: at most +${f0(worst)} ns over native (${ROUND_TRIP_US.map(us => `${(worst / (us * 1000) * 100).toFixed(2)}% of ${us} µs`).join(", ")}), ` +
    `and ${worstC >= 0 ? "+" : ""}${f0(worstC)} ns at most over form C.`);

  // Ticks.
  line();
  line("### Microtask ticks from settle to the consumer's next line");
  line();
  const tickKeys = Object.keys(first.ticks.native);
  const consistent = runs.every(r => JSON.stringify(r.report.ticks) === JSON.stringify(first.ticks));
  line(`0 = the consumer ran before any microtask queued right after the settle. ${consistent ? "Identical in every run." : "**Differs between runs** (first run shown)."}`);
  line();
  line(`| Variant | ${tickKeys.join(" | ")} |`);
  line(`|---|${tickKeys.map(() => "---:").join("|")}|`);
  for (const v of variants) line(`| ${labels[v]} | ${tickKeys.map(k => first.ticks[v][k]).join(" | ")} |`);

  // Order.
  line();
  line("### Order: call X settled first, then a native promise N, in one task");
  line();
  const orderKeys = Object.keys(first.order.native);
  const orderConsistent = runs.every(r => JSON.stringify(r.report.order) === JSON.stringify(first.order));
  line(`\`XN\` = X continued first (settle order kept); \`NX\` = the later native promise overtook X. ${orderConsistent ? "Identical in every run." : "**Differs between runs** (first run shown)."}`);
  line();
  line(`| Variant | ${orderKeys.join(" | ")} |`);
  line(`|---|${orderKeys.map(() => "---|").join("")}`);
  for (const v of variants) line(`| ${labels[v]} | ${orderKeys.map(k => first.order[v][k]).join(" | ")} |`);

  // Heap.
  const heap = first.heap ?? {};
  if (heap.allocatedPerCall) {
    line();
    line("### Bytes allocated per call on the timed path (V8 heap counter, differenced batches)");
    line();
    line(`Method control: one \`{a, b}\` literal measured ${runs.map(r => f1(r.report.heap.controlObjectBytes.median)).join(", ")} bytes. Median per run, then the range across runs.`);
    line();
    line(`| Variant | ${styles.join(" | ")} |`);
    line(`|---|${styles.map(() => "---:").join("|")}|`);
    for (const v of variants) {
      line(`| ${labels[v]} | ${styles.map(s => { const m = runs.map(r => r.report.heap.allocatedPerCall[`${v}.${s}`].median as number); return `${f0(median(m))} [${f0(Math.min(...m))}–${f0(Math.max(...m))}]`; }).join(" | ")} |`);
    }
  }

  if (heap.retained) {
    const source = heap.retained["native.none"][0].source;
    line();
    line(`### Bytes retained per outstanding call (${source}, ${first.options.retainedCount} calls)`);
    line();
    line(`"pending" = the call alone; the other columns add an awaiting consumer (async function) per call. Median of ${runs.length * heap.retained["native.none"].length} measurements${source === "process RSS" ? "; RSS is coarse (GC timing, page granularity)" : ""}.`);
    line();
    const cols = ["none", ...styles];
    line(`| Variant | ${cols.map(c => c === "none" ? "pending" : c).join(" | ")} |`);
    line(`|---|${cols.map(() => "---:").join("|")}|`);
    for (const v of variants) {
      line(`| ${labels[v]} | ${cols.map(c => f0(median(runs.flatMap(r => (r.report.heap.retained[`${v}.${c}`] as Json[]).map(x => x.bytesPerCall))))).join(" | ")} |`);
    }
  }

  // Burst.
  line();
  line(`### Burst: ${first.burst.size} outstanding calls with awaiting consumers, settled in one task`);
  line();
  const hasHeap = first.burst.runs["native.await"][0].peakBytes !== undefined;
  line(`Time from the first settle until every consumer has continued: mean over ${runs.length} × ${first.options.burstRounds} bursts (a mean, so that a coarse clock still averages out)` +
    (hasHeap ? "; peak = heap growth with all calls outstanding, before GC; retained = after a forced GC (MB)." : "."));
  line();
  line(`| Variant | ${styles.map(s => `${s}: ms${hasHeap ? " / peak / retained" : ""}`).join(" | ")} |`);
  line(`|---|${styles.map(() => "---:").join("|")}|`);
  for (const v of variants) {
    line(`| ${labels[v]} | ${styles.map(s => {
      const all = runs.flatMap(r => r.report.burst.runs[`${v}.${s}`] as Json[]);
      const ms = all.reduce((sum, x) => sum + x.ms, 0) / all.length;
      if (hasHeap) return `${f2(ms)} / ${f1(median(all.map(x => x.peakBytes / 1e6)))} / ${f1(median(all.map(x => x.retainedBytes / 1e6)))}`;
      return f2(ms);
    }).join(" | ")} |`);
  }

  // Parity.
  line();
  line("### Parity");
  line();
  const keys = Object.keys(first.parity.subclass);
  const parityConsistent = runs.every(r => JSON.stringify(r.report.parity) === JSON.stringify(first.parity));
  line(parityConsistent ? "Identical in every run." : "**Differs between runs** (first run shown).");
  line();
  line(`| Check | ${variants.map(v => labels[v]).join(" | ")} |`);
  line(`|---|${variants.map(() => "---|").join("")}`);
  for (const k of keys) line(`| ${k} | ${variants.map(v => String(first.parity[v][k]).replaceAll("|", "\\|")).join(" | ")} |`);
}

// JSC memory: one fresh WebKitGTK process per reading (results/raw/memory/memory-<engine>-<variant>-<style>-<run>.json).
const memoryDir = join(rawDir, "memory");
if (existsSync(memoryDir)) {
  const readings = new Map<string, number[]>();
  let engine = "";
  let count = 0;
  for (const file of readdirSync(memoryDir).filter(f => f.endsWith(".json"))) {
    const r = JSON.parse(readFileSync(join(memoryDir, file), "utf8"));
    if (r.error) { console.error(`${file}: ${r.error}`); continue; }
    engine = r.engine;
    count = r.count;
    const key = `${r.variant || "control"}.${r.style}`;
    (readings.get(key) ?? readings.set(key, []).get(key)!).push(r.bytesPerCall);
  }

  const control = (readings.get("control.control") ?? []).map(f0).join(", ");
  line();
  line(`## ${engine}: bytes per outstanding call from process RSS, fresh process per reading`);
  line();
  line(`Each reading starts a new WebKitGTK process, creates ${count} calls and reads the WebKitWebProcess RSS before and after. ` +
    "No GC is forced (JSC offers pages none), so short-lived garbage such as the executor closure is included. " +
    `Method control: one \`{a, b}\` literal plus its array slot measured ${control} bytes. ` +
    `Median of ${readings.get("native.none")?.length ?? 0} readings, range in brackets.`);
  line();
  const cols = ["none", ...styles];
  line(`| Variant | ${cols.map(c => c === "none" ? "pending" : c).join(" | ")} |`);
  line(`|---|${cols.map(() => "---:").join("|")}|`);
  for (const v of variants) {
    line(`| ${labels[v]} | ${cols.map(c => {
      const xs = readings.get(`${v}.${c}`) ?? [];
      return xs.length ? `${f0(median(xs))} [${f0(Math.min(...xs))}–${f0(Math.max(...xs))}]` : "–";
    }).join(" | ")} |`);
  }
}

// Same-variant settle order (results/raw/order/order-<engine>.json): two calls A then B settled in one task.
const orderDir = join(rawDir, "order");
if (existsSync(orderDir)) {
  const reports = readdirSync(orderDir).filter(f => f.endsWith(".json")).sort().map(f => JSON.parse(readFileSync(join(orderDir, f), "utf8")));
  const first = reports[0];
  const keys = Object.keys(first.native);
  const identical = reports.every(r => variants.every(v => JSON.stringify(r[v]) === JSON.stringify(first[v])));
  line();
  line("## Settle order between two calls of the same variant");
  line();
  line(`A then B settled in one task; each consumed with one of await, match, unwrap, then, all (${keys.length} style pairs, pending and already settled). ` +
    `Engines: ${reports.map(r => r.engine).join(", ")}; ${identical ? "the results are identical on every engine" : "**the engines differ** (first shown)"}.`);
  line();
  line("| Variant | order kept | same style reversed | pairs that differ from native |");
  line("|---|---:|---|---|");
  for (const v of variants) {
    const kept = keys.filter(k => first[v][k] === "AB").length;
    const sameReversed = keys.filter(k => { const [a, b] = k.split(".")[1]!.split("/"); return a === b && first[v][k] !== "AB"; });
    const differs = keys.filter(k => first[v][k] !== first.native[k]);
    line(`| ${labels[v]} | ${kept}/${keys.length} | ${sameReversed.join(", ") || "none"} | ${differs.length ? `${differs.length}: ${differs.join(", ")}` : "none"} |`);
  }
}

// Control: the native baseline in a Node process that never defined a Promise subclass.
const controlDir = join(rawDir, "controls");
if (existsSync(controlDir)) {
  const reports = readdirSync(controlDir).filter(f => f.startsWith("control-native-alone")).sort().map(f => JSON.parse(readFileSync(join(controlDir, f), "utf8")));
  line();
  line("## Control: native baseline alone (Node, no subclass defined in the process)");
  line();
  line(`Per-run medians, ${reports.length} runs, ns per call.`);
  line();
  line(`| | ${styles.join(" | ")} |`);
  line(`|---|${styles.map(() => "---:").join("|")}|`);
  line(`| native alone | ${styles.map(s => reports.map(r => f1(median(r.samples[s]))).join(", ")).join(" | ")} |`);
}

writeFileSync(outFile, out.join("\n") + "\n");
console.log(out.join("\n"));
