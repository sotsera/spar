using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Spike.Generator;

/// <summary>Emits the contract manifest (JSON) and one TypeScript module per contract.</summary>
public static class ClientEmitter
{
    public static string EmitManifest(IReadOnlyList<ContractModel> contracts)
    {
        var sb = new StringBuilder("{\"schema\":\"spar-contracts/1\",\"contracts\":[");
        sb.Append(string.Join(",", contracts.OrderBy(c => c.WireName, System.StringComparer.Ordinal).Select(contract =>
            "{\"name\":\"" + contract.WireName + "\",\"commands\":["
            + string.Join(",", contract.Commands.Select(command =>
                "{\"name\":\"" + command.WireName + "\""
                + (command.Request is null ? string.Empty : ",\"request\":\"" + TsType(command.Request) + "\"")
                + ",\"response\":\"" + TsType(command.Response) + "\""
                + (command.Kind == CommandKind.Unary ? string.Empty : ",\"kind\":\"" + (command.Kind == CommandKind.Stream ? "stream" : "subscription") + "\"")
                + "}"))
            + "]}")));
        sb.Append("]}");
        return sb.ToString();
    }

    public static string EmitTypeScript(ContractModel contract)
    {
        var sb = new StringBuilder("// Generated by Spar. Do not edit.\n");
        sb.AppendLine("import { invoke } from \"./transport.js\";");
        foreach (var dto in contract.Dtos.OrderBy(d => d.Name, System.StringComparer.Ordinal))
        {
            sb.AppendLine();
            sb.AppendLine($"export interface {dto.Name} {{");
            foreach (var property in dto.Properties)
            {
                sb.AppendLine($"  readonly {property.JsonName}: {TsType(property.Type)};");
            }

            sb.AppendLine("}");
        }

        sb.AppendLine();
        sb.AppendLine($"export const {contract.WireName} = {{");
        foreach (var command in contract.Commands.Where(c => c.Kind == CommandKind.Unary))
        {
            var parameter = command.Request is null ? string.Empty : $"request: {TsType(command.Request)}";
            var argument = command.Request is null ? "undefined" : "request";
            sb.AppendLine($"  {command.WireName}: ({parameter}) => invoke<{TsType(command.Response)}>(\"{contract.WireName}\", \"{command.WireName}\", {argument}),");
        }

        sb.AppendLine("} as const;");
        return sb.ToString();
    }

    /// <summary>
    /// Plain ES module for a contract, for frontends without a TypeScript build. Every call sends the
    /// contract fingerprint so a host built from different contracts rejects it instead of mis-dispatching.
    /// </summary>
    public static string EmitJavaScript(ContractModel contract, string fingerprint, string sdkModule = "./spar-sdk.js")
    {
        var sb = new StringBuilder("// Generated by Spar. Do not edit.\n");
        sb.Append($"import {{ invoke }} from \"{sdkModule}\";\n\n");
        sb.Append($"export const fingerprint = \"{fingerprint}\";\n\n");
        sb.Append($"export const {contract.WireName} = {{\n");
        foreach (var command in contract.Commands.Where(c => c.Kind == CommandKind.Unary))
        {
            var parameter = command.Request is null ? "options" : "request, options";
            var argument = command.Request is null ? "undefined" : "request";
            sb.Append($"  {command.WireName}: ({parameter}) => invoke(fingerprint, \"{contract.WireName}\", \"{command.WireName}\", {argument}, options?.signal),\n");
        }

        sb.Append("};\n");
        return sb.ToString();
    }

    /// <summary>
    /// A contract package as TypeScript source, compiled by the application's own toolchain. It must type-check
    /// under strict consumer settings (strict, verbatimModuleSyntax, noUnusedLocals, isolatedModules, erasable syntax).
    /// </summary>
    public static string EmitPackageTypeScript(ContractModel contract, string fingerprint, string sdkModule)
    {
        // Import only what this contract uses: consumers compile with noUnusedLocals.
        var kinds = new HashSet<CommandKind>(contract.Commands.Select(c => c.Kind));
        var imports = new List<string>();
        if (kinds.Contains(CommandKind.Unary)) imports.Add("invoke");
        if (kinds.Contains(CommandKind.Stream)) imports.Add("stream");
        if (kinds.Contains(CommandKind.Subscription)) imports.Add("subscribe");
        imports.Add("type CallOptions");
        if (kinds.Contains(CommandKind.Stream) || kinds.Contains(CommandKind.Subscription)) imports.Add("type StreamOptions");
        if (kinds.Contains(CommandKind.Subscription)) imports.Add("type SubscriptionEvent");

        var sb = new StringBuilder("// Generated by Spar. Do not edit.\n");
        sb.Append($"import {{ {string.Join(", ", imports)} }} from \"{sdkModule}\";\n\n");
        sb.Append($"export type {{ {string.Join(", ", imports.Where(i => i.StartsWith("type ", System.StringComparison.Ordinal)).Select(i => i.Substring(5)))} }};\n");
        foreach (var dto in contract.Dtos.OrderBy(d => d.Name, System.StringComparer.Ordinal))
        {
            sb.Append($"\nexport interface {dto.Name} {{\n");
            foreach (var property in dto.Properties)
            {
                sb.Append($"  readonly {property.JsonName}: {TsType(property.Type)};\n");
            }

            sb.Append("}\n");
        }

        sb.Append($"\nexport const fingerprint = \"{fingerprint}\";\n\n");
        sb.Append($"export const {contract.WireName} = {{\n");
        foreach (var command in contract.Commands)
        {
            var response = TsType(command.Response);
            var optionsType = command.Kind == CommandKind.Unary ? "CallOptions" : "StreamOptions";
            var parameters = command.Request is null ? $"options?: {optionsType}" : $"request: {TsType(command.Request)}, options?: {optionsType}";
            var argument = command.Request is null ? "undefined" : "request";
            switch (command.Kind)
            {
                case CommandKind.Unary:
                    sb.Append($"  {command.WireName}: ({parameters}): Promise<{response}> =>\n");
                    sb.Append($"    invoke<{response}>(fingerprint, \"{contract.WireName}\", \"{command.WireName}\", {argument}, options?.signal),\n");
                    break;
                case CommandKind.Stream:
                    sb.Append($"  {command.WireName}: ({parameters}): AsyncIterable<{response}> =>\n");
                    sb.Append($"    stream<{response}>(fingerprint, \"{contract.WireName}\", \"{command.WireName}\", {argument}, options),\n");
                    break;
                case CommandKind.Subscription:
                    sb.Append($"  {command.WireName}: ({parameters}): AsyncIterable<SubscriptionEvent<{response}>> =>\n");
                    sb.Append($"    subscribe<{response}>(fingerprint, \"{contract.WireName}\", \"{command.WireName}\", {argument}, options),\n");
                    break;
            }
        }

        sb.Append("} as const;\n");
        return sb.ToString();
    }

    /// <summary>Type declarations for a contract package: DTO interfaces and the typed command object.</summary>
    public static string EmitDeclarations(ContractModel contract)
    {
        var sb = new StringBuilder("// Generated by Spar. Do not edit.\n");
        foreach (var dto in contract.Dtos.OrderBy(d => d.Name, System.StringComparer.Ordinal))
        {
            sb.Append($"\nexport interface {dto.Name} {{\n");
            foreach (var property in dto.Properties)
            {
                sb.Append($"  readonly {property.JsonName}: {TsType(property.Type)};\n");
            }

            sb.Append("}\n");
        }

        sb.Append("\nexport declare const fingerprint: string;\n\n");
        sb.Append("export interface CallOptions {\n  readonly signal?: AbortSignal;\n}\n\n");
        sb.Append($"export declare const {contract.WireName}: {{\n");
        foreach (var command in contract.Commands.Where(c => c.Kind == CommandKind.Unary))
        {
            var parameter = command.Request is null ? "options?: CallOptions" : $"request: {TsType(command.Request)}, options?: CallOptions";
            sb.Append($"  {command.WireName}({parameter}): Promise<{TsType(command.Response)}>;\n");
        }

        sb.Append("};\n");
        return sb.ToString();
    }

    private static string TsType(TypeRef type)
    {
        var ts = type.Kind switch
        {
            WireKind.String => "string",
            WireKind.Int32 or WireKind.Int64 or WireKind.Double => "number",
            WireKind.Boolean => "boolean",
            WireKind.Array => $"readonly {Wrap(TsType(type.Element!))}[]",
            WireKind.Dto => type.DtoName!.Substring(type.DtoName.LastIndexOf('.') + 1),
            _ => "unknown",
        };

        return type.Nullable ? ts + " | null" : ts;
    }

    private static string Wrap(string ts) => ts.Contains(" ") ? $"({ts})" : ts;
}
