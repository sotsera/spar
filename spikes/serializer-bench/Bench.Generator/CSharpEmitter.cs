using System.Collections.Generic;
using System.Text;

namespace Bench.Generator;

/// <summary>
/// Emits the generated serializers and, per contract, a codec class that exposes exactly the
/// parse and write code the spike's dispatch binding used, so a benchmark can call it directly.
/// </summary>
public static class CSharpEmitter
{
    private const string Header = "// <auto-generated/>\n#nullable enable\n";

    public static string EmitCodec(ContractModel contract)
    {
        var sb = new StringBuilder(Header);
        sb.AppendLine("using global::System.Text.Json;");
        sb.AppendLine();
        sb.AppendLine("namespace Spar.Generated;");
        sb.AppendLine();
        sb.AppendLine($"internal static class {contract.TypeName}Codec");
        sb.AppendLine("{");
        foreach (var command in contract.Commands)
        {
            if (command.Request is { } parsed)
            {
                // Same body as the binding's Parse{Method}, taking the span the binding read from payload.Span.
                sb.AppendLine($"    public static {Declared(parsed)} Parse{command.MethodName}(global::System.ReadOnlySpan<byte> payload)");
                sb.AppendLine("    {");
                sb.AppendLine("        var reader = global::Bench.SparJson.Begin(payload);");
                sb.AppendLine($"        return {ReadValue(parsed, "reader")};");
                sb.AppendLine("    }");
                sb.AppendLine();
            }

            // Same expression as the binding's response write.
            sb.AppendLine($"    public static byte[] Serialize{command.MethodName}({Declared(command.Response)} result) =>");
            sb.AppendLine($"        global::Bench.SparJson.Write(result, static (writer, v) => {{ {WriteValue(command.Response, "v", 0)} }});");
            sb.AppendLine();

            // The same write body against a caller-supplied writer (pooled-buffer variant).
            sb.AppendLine($"    public static void Write{command.MethodName}(Utf8JsonWriter writer, {Declared(command.Response)} v)");
            sb.AppendLine("    {");
            sb.AppendLine($"        {WriteValue(command.Response, "v", 0)}");
            sb.AppendLine("    }");
            sb.AppendLine();

            // Experiment: the tuned writer (pre-encoded names, indexed loops) against a caller-supplied writer.
            sb.AppendLine($"    public static void WriteTuned{command.MethodName}(Utf8JsonWriter writer, {Declared(command.Response)} v)");
            sb.AppendLine("    {");
            sb.AppendLine($"        {TunedValue(command.Response, "v", 0)}");
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    public static string EmitSerializers(IEnumerable<DtoModel> dtos)
    {
        var sb = new StringBuilder(Header);
        sb.AppendLine("using global::System.Text.Json;");
        sb.AppendLine();
        sb.AppendLine("namespace Spar.Generated;");
        sb.AppendLine();
        sb.AppendLine("internal static class SparSerializers");
        sb.AppendLine("{");
        foreach (var dto in dtos)
        {
            EmitReader(sb, dto);
            EmitWriter(sb, dto);
            EmitTunedWriter(sb, dto);
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void EmitReader(StringBuilder sb, DtoModel dto)
    {
        sb.AppendLine($"    public static {dto.CSharp} Read{dto.Name}(ref Utf8JsonReader reader)");
        sb.AppendLine("    {");
        sb.AppendLine("        if (reader.TokenType != JsonTokenType.StartObject)");
        sb.AppendLine("        {");
        sb.AppendLine($"            throw new JsonException($\"Expected an object for {dto.Name} but found {{reader.TokenType}}.\");");
        sb.AppendLine("        }");
        sb.AppendLine();
        var index = 0;
        foreach (var property in dto.Properties)
        {
            sb.AppendLine($"        {Local(property.Type)} p{index} = default;");
            if (!property.Type.Nullable)
            {
                sb.AppendLine($"        var has{index} = false;");
            }
            index++;
        }

        sb.AppendLine("        while (reader.Read() && reader.TokenType != JsonTokenType.EndObject)");
        sb.AppendLine("        {");
        index = 0;
        foreach (var property in dto.Properties)
        {
            var keyword = index == 0 ? "if" : "else if";
            sb.AppendLine($"            {keyword} (reader.ValueTextEquals(\"{property.JsonName}\"u8))");
            sb.AppendLine("            {");
            sb.AppendLine("                reader.Read();");
            sb.AppendLine($"                p{index} = {ReadValue(property.Type, "reader")};");
            if (!property.Type.Nullable)
            {
                sb.AppendLine($"                has{index} = true;");
            }
            sb.AppendLine("            }");
            index++;
        }

        sb.AppendLine("            else");
        sb.AppendLine("            {");
        sb.AppendLine("                reader.Read();");
        sb.AppendLine("                reader.Skip();");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
        sb.AppendLine();
        index = 0;
        var arguments = new List<string>();
        foreach (var property in dto.Properties)
        {
            if (!property.Type.Nullable)
            {
                sb.AppendLine($"        if (!has{index}) throw new JsonException(\"{dto.Name} requires '{property.JsonName}'.\");");
                arguments.Add(IsValueType(property.Type) ? $"p{index}" : $"p{index}!");
            }
            else
            {
                arguments.Add($"p{index}");
            }

            index++;
        }

        sb.AppendLine($"        return new {dto.CSharp}({string.Join(", ", arguments)});");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitWriter(StringBuilder sb, DtoModel dto)
    {
        sb.AppendLine($"    public static void Write{dto.Name}(Utf8JsonWriter writer, {dto.CSharp} value)");
        sb.AppendLine("    {");
        sb.AppendLine("        writer.WriteStartObject();");
        foreach (var property in dto.Properties)
        {
            sb.AppendLine($"        writer.WritePropertyName(\"{property.JsonName}\"u8);");
            sb.AppendLine($"        {WriteValue(property.Type, $"value.{property.Name}", 2)}");
        }

        sb.AppendLine("        writer.WriteEndObject();");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    // Experiment, not in the D1 emitter: property names pre-encoded once as JsonEncodedText and written with the
    // combined name+value overloads, and list properties written by index so no enumerator is boxed.
    private static void EmitTunedWriter(StringBuilder sb, DtoModel dto)
    {
        sb.AppendLine($"    private static class {dto.Name}Names");
        sb.AppendLine("    {");
        foreach (var property in dto.Properties)
        {
            sb.AppendLine($"        public static readonly JsonEncodedText {property.Name} = JsonEncodedText.Encode(\"{property.JsonName}\"u8);");
        }

        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine($"    public static void WriteTuned{dto.Name}(Utf8JsonWriter writer, {dto.CSharp} value)");
        sb.AppendLine("    {");
        sb.AppendLine("        writer.WriteStartObject();");
        foreach (var property in dto.Properties)
        {
            sb.AppendLine($"        {TunedProperty(property.Type, $"{dto.Name}Names.{property.Name}", $"value.{property.Name}", 2)}");
        }

        sb.AppendLine("        writer.WriteEndObject();");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static string TunedProperty(TypeRef type, string name, string value, int depth)
    {
        var write = type.Kind switch
        {
            WireKind.String => $"writer.WriteString({name}, {value});",
            WireKind.Int32 or WireKind.Int64 or WireKind.Double => $"writer.WriteNumber({name}, {ValueOf(type, value)});",
            WireKind.Boolean => $"writer.WriteBoolean({name}, {ValueOf(type, value)});",
            WireKind.Array => $"writer.WriteStartArray({name}); {TunedItems(type, value, depth)} writer.WriteEndArray();",
            WireKind.Dto => $"writer.WritePropertyName({name}); global::Spar.Generated.SparSerializers.WriteTuned{ShortName(type)}(writer, {value});",
            _ => throw new System.InvalidOperationException(type.Kind.ToString()),
        };

        return type.Nullable && type.Kind != WireKind.String
            ? $"if ({value} is null) {{ writer.WriteNull({name}); }} else {{ {write} }}"
            : write;
    }

    private static string TunedValue(TypeRef type, string value, int depth)
    {
        var write = type.Kind switch
        {
            WireKind.Array => $"writer.WriteStartArray(); {TunedItems(type, value, depth)} writer.WriteEndArray();",
            WireKind.Dto => $"global::Spar.Generated.SparSerializers.WriteTuned{ShortName(type)}(writer, {value});",
            _ => WriteValue(type, value, depth),
        };

        return type.Nullable && type.Kind is WireKind.Array or WireKind.Dto
            ? $"if ({value} is null) {{ writer.WriteNullValue(); }} else {{ {write} }}"
            : write;
    }

    private static string TunedItems(TypeRef type, string value, int depth)
    {
        var count = type.CSharp.EndsWith("[]", System.StringComparison.Ordinal) ? "Length" : "Count";
        return $"{{ var list{depth} = {value}; for (var i{depth} = 0; i{depth} < list{depth}.{count}; i{depth}++) {{ {TunedValue(type.Element!, $"list{depth}[i{depth}]", depth + 1)} }} }}";
    }

    private static string ReadValue(TypeRef type, string reader)
    {
        var read = type.Kind switch
        {
            WireKind.String => $"global::Bench.SparJson.ReadString(ref {reader})",
            WireKind.Int32 => $"{reader}.GetInt32()",
            WireKind.Int64 => $"{reader}.GetInt64()",
            WireKind.Double => $"{reader}.GetDouble()",
            WireKind.Boolean => $"{reader}.GetBoolean()",
            WireKind.Array => $"global::Bench.SparJson.ReadArray<{Declared(type.Element!)}>(ref {reader}, static (ref Utf8JsonReader r) => {ReadValue(type.Element!, "r")})",
            WireKind.Dto => $"global::Spar.Generated.SparSerializers.Read{ShortName(type)}(ref {reader})",
            _ => throw new System.InvalidOperationException(type.Kind.ToString()),
        };

        return type.Nullable ? $"{reader}.TokenType == JsonTokenType.Null ? null : {read}" : read;
    }

    private static string WriteValue(TypeRef type, string value, int depth)
    {
        var write = type.Kind switch
        {
            WireKind.String => $"writer.WriteStringValue({value});",
            WireKind.Int32 or WireKind.Int64 or WireKind.Double => $"writer.WriteNumberValue({ValueOf(type, value)});",
            WireKind.Boolean => $"writer.WriteBooleanValue({ValueOf(type, value)});",
            WireKind.Array => $"writer.WriteStartArray(); foreach (var e{depth} in {value}) {{ {WriteValue(type.Element!, $"e{depth}", depth + 1)} }} writer.WriteEndArray();",
            WireKind.Dto => $"global::Spar.Generated.SparSerializers.Write{ShortName(type)}(writer, {value});",
            _ => throw new System.InvalidOperationException(type.Kind.ToString()),
        };

        return type.Nullable ? $"if ({value} is null) {{ writer.WriteNullValue(); }} else {{ {write} }}" : write;
    }

    private static string ValueOf(TypeRef type, string value) => type.Nullable ? $"{value}.Value" : value;

    private static string ShortName(TypeRef type) => type.DtoName!.Substring(type.DtoName.LastIndexOf('.') + 1);

    private static string Declared(TypeRef type) => type.Kind == WireKind.Array
        ? $"{Declared(type.Element!)}[]{(type.Nullable ? "?" : string.Empty)}"
        : type.CSharp + (type.Nullable ? "?" : string.Empty);

    private static string Local(TypeRef type)
    {
        var declared = Declared(type);
        return IsValueType(type) || declared.EndsWith("?", System.StringComparison.Ordinal) ? declared : declared + "?";
    }

    private static bool IsValueType(TypeRef type) =>
        type.Kind is WireKind.Int32 or WireKind.Int64 or WireKind.Double or WireKind.Boolean;
}
