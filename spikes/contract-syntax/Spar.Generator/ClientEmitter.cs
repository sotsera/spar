using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Spar.Generator;

/// <summary>
/// Emits the contract manifest (JSON) and the TypeScript packages: one package per contract, plus one module per
/// type that two or more contracts share. A shared type is declared once and re-exported by every contract package
/// that uses it, so same-named types of different contracts never meet in one module.
/// </summary>
public static class ClientEmitter
{
    private const string Banner = "// Generated by Spar. Do not edit.\n";

    /// <summary>The spike's stand-in SDK. Results are plain data here; the opaque result shape is designed separately.</summary>
    public const string SdkTypeScript = Banner
        + "export interface CallOptions {\n"
        + "  readonly signal?: AbortSignal;\n"
        + "}\n\n"
        + "/** A command's outcome when it declares expected errors. */\n"
        + "export type Result<T, E> =\n"
        + "  | { readonly ok: true; readonly value: T }\n"
        + "  | { readonly ok: false; readonly error: E };\n\n"
        + "export interface Transport {\n"
        + "  invoke(contract: string, command: string, request: unknown, signal?: AbortSignal): Promise<unknown>;\n"
        + "  stream(contract: string, command: string, request: unknown, signal?: AbortSignal): AsyncIterable<unknown>;\n"
        + "}\n\n"
        + "let transport: Transport | undefined;\n\n"
        + "export function configureTransport(value: Transport): void {\n"
        + "  transport = value;\n"
        + "}\n\n"
        + "function current(): Transport {\n"
        + "  if (transport === undefined) {\n"
        + "    throw new Error(\"No Spar transport is configured.\");\n"
        + "  }\n\n"
        + "  return transport;\n"
        + "}\n\n"
        + "export function invoke<T>(contract: string, command: string, request: unknown, options?: CallOptions): Promise<T> {\n"
        + "  return current().invoke(contract, command, request, options?.signal) as Promise<T>;\n"
        + "}\n\n"
        + "export function stream<T>(contract: string, command: string, request: unknown, options?: CallOptions): AsyncIterable<T> {\n"
        + "  return current().stream(contract, command, request, options?.signal) as AsyncIterable<T>;\n"
        + "}\n";

    public static string EmitManifest(EquatableArray<ContractModel> contracts)
    {
        var names = TypeNames(contracts);
        var sb = new StringBuilder("{\"schema\":\"spar-contracts/2\",\"contracts\":[");
        sb.Append(string.Join(",", contracts.Select(contract =>
            "{\"name\":\"" + contract.WireName + "\",\"form\":\"" + contract.Form.ToString().ToLowerInvariant() + "\",\"commands\":["
            + string.Join(",", contract.Commands.Select(command =>
                "{\"name\":\"" + command.WireName + "\",\"kind\":\"" + command.Kind.ToString().ToLowerInvariant() + "\""
                + (command.Request is null ? string.Empty : ",\"request\":\"" + TsType(command.Request, names) + "\"")
                + ",\"response\":\"" + TsType(command.Response, names) + "\""
                + (command.Error is null ? string.Empty : ",\"error\":\"" + TsType(command.Error, names) + "\"")
                + "}"))
            + "]}")));
        sb.Append("]}");
        return sb.ToString();
    }

    /// <summary>Every client file, keyed by its path relative to the client folder ('/' separators).</summary>
    public static SortedDictionary<string, string> EmitPackages(EquatableArray<ContractModel> contracts)
    {
        var files = new SortedDictionary<string, string>(System.StringComparer.Ordinal);
        var names = TypeNames(contracts);
        var declarations = new Dictionary<string, (string Code, List<string> Uses)>();
        foreach (var dto in contracts.SelectMany(c => c.Dtos))
        {
            declarations[dto.Key] = DeclareDto(dto, names);
        }

        foreach (var error in contracts.SelectMany(c => c.Errors))
        {
            declarations[error.Key] = DeclareError(error, names);
        }

        var shared = new HashSet<string>(contracts
            .SelectMany(c => c.Dtos.Select(d => d.Key).Concat(c.Errors.Select(e => e.Key)))
            .GroupBy(k => k)
            .Where(g => g.Count() > 1)
            .Select(g => g.Key));

        files["packages/@spar/sdk/package.json"] = PackageJson("sdk");
        files["packages/@spar/sdk/index.ts"] = SdkTypeScript;
        foreach (var key in shared)
        {
            var (code, uses) = declarations[key];
            var sb = new StringBuilder(Banner);
            var imports = uses.Where(u => u != key).Distinct().OrderBy(u => names[u], System.StringComparer.Ordinal).ToList();
            foreach (var use in imports)
            {
                sb.Append($"import type {{ {names[use]} }} from \"./{ModuleName(use)}.js\";\n");
            }

            sb.Append(imports.Count > 0 ? "\n" : string.Empty).Append(code);
            files[$"packages/@spar/shared/{ModuleName(key)}.ts"] = sb.ToString();
        }

        foreach (var contract in contracts)
        {
            files[$"packages/@spar/{contract.WireName}/package.json"] = PackageJson(contract.WireName);
            files[$"packages/@spar/{contract.WireName}/index.ts"] = EmitContract(contract, names, declarations, shared);
        }

        return files;
    }

    private static string EmitContract(
        ContractModel contract,
        Dictionary<string, string> names,
        Dictionary<string, (string Code, List<string> Uses)> declarations,
        HashSet<string> shared)
    {
        var keys = contract.Dtos.Select(d => d.Key).Concat(contract.Errors.Select(e => e.Key)).ToList();
        var sharedKeys = keys.Where(shared.Contains).OrderBy(k => names[k], System.StringComparer.Ordinal).ToList();
        var localKeys = keys.Where(k => !shared.Contains(k)).OrderBy(k => names[k], System.StringComparer.Ordinal).ToList();

        var sb = new StringBuilder(Banner);
        sb.Append("import * as spar from \"../sdk/index.js\";\n");
        foreach (var key in sharedKeys)
        {
            sb.Append($"import type {{ {names[key]} }} from \"../shared/{ModuleName(key)}.js\";\n");
        }

        if (sharedKeys.Count > 0)
        {
            sb.Append($"\nexport type {{ {string.Join(", ", sharedKeys.Select(k => names[k]))} }};\n");
        }

        foreach (var key in localKeys)
        {
            sb.Append('\n').Append(declarations[key].Code);
        }

        sb.Append($"\nexport const {contract.WireName} = {{\n");
        foreach (var command in contract.Commands)
        {
            var value = TsType(command.Response, names);
            var parameters = command.Request is null
                ? "options?: spar.CallOptions"
                : $"request: {TsType(command.Request, names)}, options?: spar.CallOptions";
            var argument = command.Request is null ? "undefined" : "request";
            if (command.Kind == CommandKind.Stream)
            {
                sb.Append($"  {command.WireName}: ({parameters}): AsyncIterable<{value}> =>\n");
                sb.Append($"    spar.stream<{value}>(\"{contract.WireName}\", \"{command.WireName}\", {argument}, options),\n");
                continue;
            }

            var result = command.Error is null ? value : $"spar.Result<{value}, {TsType(command.Error, names)}>";
            sb.Append($"  {command.WireName}: ({parameters}): Promise<{result}> =>\n");
            sb.Append($"    spar.invoke<{result}>(\"{contract.WireName}\", \"{command.WireName}\", {argument}, options),\n");
        }

        sb.Append("} as const;\n");
        return sb.ToString();
    }

    private static (string Code, List<string> Uses) DeclareDto(DtoModel dto, Dictionary<string, string> names)
    {
        var uses = new List<string>();
        var sb = new StringBuilder($"export interface {dto.TsName} {{\n");
        foreach (var property in dto.Properties)
        {
            Collect(property.Type, uses);
            sb.Append($"  readonly {property.JsonName}: {TsType(property.Type, names)};\n");
        }

        sb.Append("}\n");
        return (sb.ToString(), uses);
    }

    private static (string Code, List<string> Uses) DeclareError(ErrorModel error, Dictionary<string, string> names)
    {
        var uses = new List<string>();
        var sb = new StringBuilder($"export type {error.TsName} =\n");
        var cases = error.Cases.ToList();
        for (var i = 0; i < cases.Count; i++)
        {
            sb.Append($"  | {{ readonly code: \"{cases[i].Code}\"");
            foreach (var property in cases[i].Properties)
            {
                Collect(property.Type, uses);
                sb.Append($"; readonly {property.JsonName}: {TsType(property.Type, names)}");
            }

            sb.Append(i == cases.Count - 1 ? " };\n" : " }\n");
        }

        return (sb.ToString(), uses);
    }

    private static void Collect(TypeRef type, List<string> uses)
    {
        if (type.Element is { } element)
        {
            Collect(element, uses);
        }
        else if (type.TypeKey is { } key)
        {
            uses.Add(key);
        }
    }

    private static Dictionary<string, string> TypeNames(EquatableArray<ContractModel> contracts)
    {
        var names = new Dictionary<string, string>();
        foreach (var dto in contracts.SelectMany(c => c.Dtos))
        {
            names[dto.Key] = dto.TsName;
        }

        foreach (var error in contracts.SelectMany(c => c.Errors))
        {
            names[error.Key] = error.TsName;
        }

        return names;
    }

    private static string TsType(TypeRef type, Dictionary<string, string> names)
    {
        var ts = type.Kind switch
        {
            WireKind.String or WireKind.Guid => "string",
            WireKind.Int32 or WireKind.Int64 or WireKind.Double => "number",
            WireKind.Boolean => "boolean",
            WireKind.Array => $"readonly {Wrap(TsType(type.Element!, names))}[]",
            WireKind.Dto or WireKind.Error => names[type.TypeKey!],
            _ => "unknown",
        };

        return type.Nullable ? ts + " | null" : ts;
    }

    private static string ModuleName(string key) => key.Replace("global::", string.Empty);

    private static string Wrap(string ts) => ts.Contains(" ") ? $"({ts})" : ts;

    private static string PackageJson(string name) =>
        $"{{\n  \"name\": \"@spar/{name}\",\n  \"private\": true,\n  \"type\": \"module\",\n  \"exports\": \"./index.ts\",\n  \"types\": \"./index.ts\",\n  \"sideEffects\": false\n}}\n";
}
