using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Spar.Generator;

/// <summary>Emits the C# dispatch, serializers and catalog for an exported contract set. Sources use '\n' only.</summary>
public static class CSharpEmitter
{
    private const string Header = "// <auto-generated/>\n#nullable enable\n\n";
    private const string Task = "global::System.Threading.Tasks.ValueTask<byte[]>";
    private const string Payload = "global::System.ReadOnlyMemory<byte> payload";
    private const string Token = "global::System.Threading.CancellationToken cancellationToken";
    private const string Services = "global::System.IServiceProvider services";

    /// <summary>All generated sources, keyed by hint name, in a stable order.</summary>
    public static List<(string HintName, string Source)> Emit(ContractSet set)
    {
        var names = SerializerNames.Create(set.Contracts);
        var sources = new List<(string, string)>
        {
            ("SparCatalog.g.cs", EmitCatalog(set.Contracts, ClientEmitter.EmitManifest(set.Contracts))),
            ("SparSerializers.g.cs", EmitSerializers(set.Contracts, names)),
        };
        foreach (var contract in set.Contracts)
        {
            sources.Add(($"SparBinding.{contract.WireName}.g.cs", EmitBinding(contract, names)));
        }

        return sources;
    }

    private static string EmitBinding(ContractModel contract, SerializerNames names)
    {
        var sb = new StringBuilder(Header);
        sb.Append("using global::Microsoft.Extensions.DependencyInjection;\n");
        sb.Append("using global::System.Text.Json;\n\n");
        sb.Append("namespace Spar.Generated;\n\n");
        sb.Append($"/// <summary>Dispatch for contract '{contract.WireName}' ({Escape(contract.CSharp)}, {contract.Form.ToString().ToLowerInvariant()} form).</summary>\n");
        sb.Append($"internal static class SparBinding_{contract.WireName}\n{{\n");

        var unary = contract.Commands.Where(c => c.Kind == CommandKind.Unary).ToList();
        var streams = contract.Commands.Where(c => c.Kind == CommandKind.Stream).ToList();

        sb.Append($"    public static {Task} InvokeAsync({Services}, string command, {Payload}, {Token}) => command switch\n    {{\n");
        foreach (var command in unary)
        {
            sb.Append($"        \"{command.WireName}\" => Command_{command.WireName}(services, payload, cancellationToken),\n");
        }

        sb.Append($"        _ => throw new global::Spar.SparUnknownCommandException($\"Unknown command '{{command}}' on contract '{contract.WireName}'.\"),\n    }};\n\n");

        sb.Append($"    public static global::Spar.SparStream OpenStream({Services}, string command, {Payload}, {Token}) => command switch\n    {{\n");
        foreach (var command in streams)
        {
            sb.Append($"        \"{command.WireName}\" => Stream_{command.WireName}(services, payload, cancellationToken),\n");
        }

        sb.Append($"        _ => throw new global::Spar.SparUnknownCommandException($\"Unknown stream '{{command}}' on contract '{contract.WireName}'.\"),\n    }};\n");

        foreach (var command in unary)
        {
            sb.Append($"\n    private static async {Task} Command_{command.WireName}({Services}, {Payload}, {Token})\n    {{\n");
            if (command.Request is not null)
            {
                sb.Append($"        var request = Parse_{command.WireName}(payload);\n");
            }

            sb.Append("        await using var scope = services.CreateAsyncScope();\n");
            sb.Append($"        var service = scope.ServiceProvider.GetRequiredService<{contract.CSharp}>();\n");
            sb.Append($"        var result = await service.{command.MethodName}({Arguments(command)}).ConfigureAwait(false);\n");
            var write = command.Error is { } error
                ? WriteResult(command.Response, error, names)
                : $"static (writer, v) => {{ {WriteValue(command.Response, "v", 0, names)} }}";
            sb.Append($"        return global::Spar.SparJson.Write(result, {write});\n    }}\n");
            EmitParse(sb, command, names);
        }

        foreach (var command in streams)
        {
            sb.Append($"\n    private static global::Spar.SparStream Stream_{command.WireName}({Services}, {Payload}, {Token})\n    {{\n");
            if (command.Request is not null)
            {
                sb.Append($"        var request = Parse_{command.WireName}(payload);\n");
            }

            sb.Append("        var scope = services.CreateAsyncScope();\n");
            sb.Append("        try\n        {\n");
            sb.Append($"            var service = scope.ServiceProvider.GetRequiredService<{contract.CSharp}>();\n");
            sb.Append($"            return global::Spar.SparStream.Create<{Declared(command.Response)}>(service.{command.MethodName}({Arguments(command)}), "
                + $"static (writer, v) => {{ {WriteValue(command.Response, "v", 0, names)} }}, scope, cancellationToken);\n");
            sb.Append("        }\n        catch\n        {\n            scope.Dispose();\n            throw;\n        }\n    }\n");
            EmitParse(sb, command, names);
        }

        sb.Append("}\n");
        return sb.ToString();
    }

    private static string Arguments(CommandModel command)
    {
        var arguments = new List<string>();
        if (command.Request is not null)
        {
            arguments.Add("request");
        }

        if (command.TakesCancellation)
        {
            arguments.Add("cancellationToken");
        }

        return string.Join(", ", arguments);
    }

    private static string WriteResult(TypeRef value, TypeRef error, SerializerNames names) =>
        "static (writer, v) => { writer.WriteStartObject(); if (v.IsError) { writer.WriteBoolean(\"ok\"u8, false); "
        + $"writer.WritePropertyName(\"error\"u8); global::Spar.Generated.SparSerializers.Write_{names[error.TypeKey!]}(writer, v.Error); }} "
        + "else { writer.WriteBoolean(\"ok\"u8, true); writer.WritePropertyName(\"value\"u8); "
        + $"{WriteValue(value, "v.Value", 0, names)} }} writer.WriteEndObject(); }}";

    private static void EmitParse(StringBuilder sb, CommandModel command, SerializerNames names)
    {
        if (command.Request is not { } request)
        {
            return;
        }

        // A request that does not parse never reaches the service: the host reports it as "not executed".
        sb.Append($"\n    private static {Declared(request)} Parse_{command.WireName}({Payload})\n    {{\n");
        sb.Append("        try\n        {\n");
        sb.Append("            var reader = global::Spar.SparJson.Begin(payload.Span);\n");
        sb.Append($"            {Declared(request)} value = {ReadValue(request, "reader", names)};\n");
        sb.Append("            global::Spar.SparJson.End(ref reader);\n");
        sb.Append("            return value;\n");
        sb.Append("        }\n");
        sb.Append("        catch (JsonException exception)\n        {\n");
        sb.Append("            throw new global::Spar.SparInvalidRequestException(exception.Message, exception);\n");
        sb.Append("        }\n    }\n");
    }

    private static string EmitCatalog(EquatableArray<ContractModel> contracts, string manifest)
    {
        var sb = new StringBuilder(Header);
        sb.Append("namespace Spar.Generated;\n\n");
        sb.Append("/// <summary>Every exported contract: local ones and those from referenced assemblies.</summary>\n");
        sb.Append("internal static class SparCatalog\n{\n");
        sb.Append($"    public const string Manifest = {Literal(manifest)};\n\n");

        sb.Append("    /// <summary>Registers class contracts as scoped services. Interface contracts need their implementation registered.</summary>\n");
        sb.Append("    public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection AddSparContracts(global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)\n    {\n");
        foreach (var contract in contracts.Where(c => c.Form == ContractForm.Class))
        {
            sb.Append($"        global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions.TryAddScoped<{contract.CSharp}>(services);\n");
        }

        sb.Append("        return services;\n    }\n\n");

        sb.Append($"    public static {Task} InvokeAsync({Services}, string contract, string command, {Payload}, {Token}) => contract switch\n    {{\n");
        foreach (var contract in contracts)
        {
            sb.Append($"        \"{contract.WireName}\" => SparBinding_{contract.WireName}.InvokeAsync(services, command, payload, cancellationToken),\n");
        }

        sb.Append("        _ => throw new global::Spar.SparUnknownCommandException($\"Unknown contract '{contract}'.\"),\n    };\n\n");

        sb.Append($"    public static global::Spar.SparStream OpenStream({Services}, string contract, string command, {Payload}, {Token}) => contract switch\n    {{\n");
        foreach (var contract in contracts)
        {
            sb.Append($"        \"{contract.WireName}\" => SparBinding_{contract.WireName}.OpenStream(services, command, payload, cancellationToken),\n");
        }

        sb.Append("        _ => throw new global::Spar.SparUnknownCommandException($\"Unknown contract '{contract}'.\"),\n    };\n}\n");
        return sb.ToString();
    }

    private static string EmitSerializers(EquatableArray<ContractModel> contracts, SerializerNames names)
    {
        var sb = new StringBuilder(Header);
        sb.Append("using global::System.Text.Json;\n\n");
        sb.Append("namespace Spar.Generated;\n\n");
        sb.Append("internal static class SparSerializers\n{\n");
        foreach (var dto in contracts.SelectMany(c => c.Dtos).GroupBy(d => d.Key).Select(g => g.First()).OrderBy(d => d.Key, System.StringComparer.Ordinal))
        {
            EmitReader(sb, dto, names);
            EmitWriter(sb, dto, names);
        }

        foreach (var error in contracts.SelectMany(c => c.Errors).GroupBy(e => e.Key).Select(g => g.First()).OrderBy(e => e.Key, System.StringComparer.Ordinal))
        {
            EmitErrorWriter(sb, error, names);
        }

        sb.Append("}\n");
        return sb.ToString();
    }

    private static void EmitReader(StringBuilder sb, DtoModel dto, SerializerNames names)
    {
        sb.Append($"    public static {dto.Key} Read_{names[dto.Key]}(ref Utf8JsonReader reader)\n    {{\n");
        sb.Append("        if (reader.TokenType != JsonTokenType.StartObject)\n        {\n");
        sb.Append($"            throw new JsonException($\"Expected an object for {dto.TsName} but found {{reader.TokenType}}.\");\n        }}\n\n");
        var index = 0;
        foreach (var property in dto.Properties)
        {
            sb.Append($"        {Local(property.Type)} p{index} = default;\n");
            if (!property.Type.Nullable)
            {
                sb.Append($"        var has{index} = false;\n");
            }

            index++;
        }

        sb.Append("        while (reader.Read() && reader.TokenType != JsonTokenType.EndObject)\n        {\n");
        index = 0;
        foreach (var property in dto.Properties)
        {
            sb.Append($"            {(index == 0 ? "if" : "else if")} (reader.ValueTextEquals(\"{property.JsonName}\"u8))\n            {{\n");
            sb.Append("                reader.Read();\n");
            sb.Append($"                p{index} = {ReadValue(property.Type, "reader", names)};\n");
            if (!property.Type.Nullable)
            {
                sb.Append($"                has{index} = true;\n");
            }

            sb.Append("            }\n");
            index++;
        }

        sb.Append(dto.Properties.Count == 0 ? "            reader.Read();\n            reader.Skip();\n" : "            else\n            {\n                reader.Read();\n                reader.Skip();\n            }\n");
        sb.Append("        }\n\n");
        index = 0;
        var arguments = new List<string>();
        foreach (var property in dto.Properties)
        {
            if (!property.Type.Nullable)
            {
                sb.Append($"        if (!has{index})\n        {{\n            throw new JsonException(\"{dto.TsName} requires '{property.JsonName}'.\");\n        }}\n\n");
                arguments.Add(IsValueType(property.Type) ? $"p{index}" : $"p{index}!");
            }
            else
            {
                arguments.Add($"p{index}");
            }

            index++;
        }

        sb.Append($"        return new {dto.Key}({string.Join(", ", arguments)});\n    }}\n\n");
    }

    private static void EmitWriter(StringBuilder sb, DtoModel dto, SerializerNames names)
    {
        sb.Append($"    public static void Write_{names[dto.Key]}(Utf8JsonWriter writer, {dto.Key} value)\n    {{\n");
        sb.Append("        writer.WriteStartObject();\n");
        foreach (var property in dto.Properties)
        {
            sb.Append($"        writer.WritePropertyName(\"{property.JsonName}\"u8);\n");
            sb.Append($"        {WriteValue(property.Type, $"value.{property.Name}", 1, names)}\n");
        }

        sb.Append("        writer.WriteEndObject();\n    }\n\n");
    }

    private static void EmitErrorWriter(StringBuilder sb, ErrorModel error, SerializerNames names)
    {
        sb.Append($"    public static void Write_{names[error.Key]}(Utf8JsonWriter writer, {error.Key} value)\n    {{\n");
        sb.Append("        writer.WriteStartObject();\n");
        sb.Append("        switch (value)\n        {\n");
        var index = 0;
        foreach (var errorCase in error.Cases)
        {
            var variable = $"c{index++}";
            sb.Append($"            case {errorCase.CSharp} {variable}:\n");
            sb.Append($"                writer.WriteString(\"code\"u8, \"{errorCase.Code}\"u8);\n");
            foreach (var property in errorCase.Properties)
            {
                sb.Append($"                writer.WritePropertyName(\"{property.JsonName}\"u8);\n");
                sb.Append($"                {WriteValue(property.Type, $"{variable}.{property.Name}", 1, names)}\n");
            }

            sb.Append("                break;\n");
        }

        sb.Append($"            default:\n                throw new global::System.InvalidOperationException($\"Unknown case of {error.TsName}: {{value.GetType().Name}}.\");\n");
        sb.Append("        }\n\n        writer.WriteEndObject();\n    }\n\n");
    }

    private static string ReadValue(TypeRef type, string reader, SerializerNames names)
    {
        var read = type.Kind switch
        {
            WireKind.String => $"global::Spar.SparJson.ReadString(ref {reader})",
            WireKind.Int32 => $"{reader}.GetInt32()",
            WireKind.Int64 => $"{reader}.GetInt64()",
            WireKind.Double => $"{reader}.GetDouble()",
            WireKind.Boolean => $"{reader}.GetBoolean()",
            WireKind.Guid => $"global::Spar.SparJson.ReadGuid(ref {reader})",
            WireKind.Array => $"global::Spar.SparJson.ReadArray<{Declared(type.Element!)}>(ref {reader}, static (ref Utf8JsonReader r) => {ReadValue(type.Element!, "r", names)})",
            WireKind.Dto => $"global::Spar.Generated.SparSerializers.Read_{names[type.TypeKey!]}(ref {reader})",
            _ => throw new System.InvalidOperationException(type.Kind.ToString()),
        };

        return type.Nullable ? $"{reader}.TokenType == JsonTokenType.Null ? null : {read}" : read;
    }

    private static string WriteValue(TypeRef type, string value, int depth, SerializerNames names)
    {
        var write = type.Kind switch
        {
            WireKind.String => $"writer.WriteStringValue({value});",
            WireKind.Guid => $"writer.WriteStringValue({ValueOf(type, value)});",
            WireKind.Int32 or WireKind.Int64 or WireKind.Double => $"writer.WriteNumberValue({ValueOf(type, value)});",
            WireKind.Boolean => $"writer.WriteBooleanValue({ValueOf(type, value)});",
            WireKind.Array => $"writer.WriteStartArray(); foreach (var e{depth} in {value}) {{ {WriteValue(type.Element!, $"e{depth}", depth + 1, names)} }} writer.WriteEndArray();",
            WireKind.Dto or WireKind.Error => $"global::Spar.Generated.SparSerializers.Write_{names[type.TypeKey!]}(writer, {value});",
            _ => throw new System.InvalidOperationException(type.Kind.ToString()),
        };

        return type.Nullable ? $"if ({value} is null) {{ writer.WriteNullValue(); }} else {{ {write} }}" : write;
    }

    private static string ValueOf(TypeRef type, string value) => type.Nullable ? $"{value}.Value" : value;

    private static string Declared(TypeRef type) => type.Kind == WireKind.Array
        ? $"{Declared(type.Element!)}[]{(type.Nullable ? "?" : string.Empty)}"
        : type.CSharp + (type.Nullable ? "?" : string.Empty);

    private static string Local(TypeRef type)
    {
        var declared = Declared(type);
        return IsValueType(type) || declared.EndsWith("?", System.StringComparison.Ordinal) ? declared : declared + "?";
    }

    private static bool IsValueType(TypeRef type) =>
        type.Kind is WireKind.Int32 or WireKind.Int64 or WireKind.Double or WireKind.Boolean or WireKind.Guid;

    private static string Escape(string value) => value.Replace("<", "&lt;").Replace(">", "&gt;");

    private static string Literal(string value) => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

    /// <summary>Unique, stable C# identifiers for the serializers of each record, from its fully qualified name.</summary>
    private sealed class SerializerNames
    {
        private readonly Dictionary<string, string> _names = [];

        public string this[string key] => _names[key];

        public static SerializerNames Create(EquatableArray<ContractModel> contracts)
        {
            var result = new SerializerNames();
            var used = new HashSet<string>(System.StringComparer.Ordinal);
            var keys = contracts.SelectMany(c => c.Dtos.Select(d => d.Key).Concat(c.Errors.Select(e => e.Key)))
                .Distinct().OrderBy(k => k, System.StringComparer.Ordinal);
            foreach (var key in keys)
            {
                var name = new string(key.Replace("global::", string.Empty).Select(c => char.IsLetterOrDigit(c) ? c : '_').ToArray());
                var unique = name;
                for (var i = 2; !used.Add(unique); i++)
                {
                    unique = name + "_" + i;
                }

                result._names[key] = unique;
            }

            return result;
        }
    }
}
