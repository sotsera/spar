using System.Collections.Immutable;
using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;

namespace Spar.Security.Generator;

/// <summary>Emits the declared policy as C# constants. Reports nothing: the analyzer owns the diagnostics.</summary>
[Generator(LanguageNames.CSharp)]
public sealed class PolicyGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // The transform yields plain strings (directive|source, permission, tt) so unchanged declarations stay cached.
        var calls = context.SyntaxProvider.CreateSyntaxProvider(
            static (node, _) => PolicyAnalysis.IsCandidate(node),
            static (syntax, cancellationToken) =>
            {
                var found = PolicyAnalysis.Analyze((InvocationExpressionSyntax)syntax.Node, syntax.SemanticModel, cancellationToken);
                if (found is null || found.Diagnostics.Count > 0)
                {
                    return ImmutableArray<string>.Empty;
                }

                return found.Sources.Select(s => "s|" + s.Key + "|" + s.Value)
                    .Concat(found.Allowed.Select(a => "p|" + a))
                    .Concat(found.TrustedTypes ? new[] { "t|" } : System.Array.Empty<string>())
                    .ToImmutableArray();
            })
            .Where(static items => !items.IsDefaultOrEmpty)
            .SelectMany(static (items, _) => items)
            .Collect();

        context.RegisterSourceOutput(calls, static (output, items) =>
        {
            var additions = new PolicyAdditions();
            foreach (var item in items)
            {
                var parts = item.Split('|');
                switch (parts[0])
                {
                    case "s":
                        additions.Sources.Add(new System.Collections.Generic.KeyValuePair<string, string>(parts[1], parts[2]));
                        break;
                    case "p":
                        additions.Allowed.Add(parts[1]);
                        break;
                    case "t":
                        additions.TrustedTypes = true;
                        break;
                }
            }

            var (csp, permissions) = PolicyAnalysis.Compose(new[] { additions });
            output.AddSource("SparSecurityPolicy.g.cs", $$"""
                // <auto-generated/>
                namespace Spar.Generated;

                /// <summary>The page security policy declared in SparApplication.Create.</summary>
                internal static class SparSecurityPolicy
                {
                    public const string ContentSecurityPolicy = {{PolicyAnalysis.Literal(csp)}};

                    public const string PermissionsPolicy = {{PolicyAnalysis.Literal(permissions)}};
                }
                """);
        });
    }
}

/// <summary>Reports the analysis's errors at their locations, on every edit (IDE) and in every build.</summary>
[DiagnosticAnalyzer(LanguageNames.CSharp)]
public sealed class PolicyAnalyzer : DiagnosticAnalyzer
{
    public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics => PolicyAnalysis.All;

    public override void Initialize(AnalysisContext context)
    {
        context.ConfigureGeneratedCodeAnalysis(GeneratedCodeAnalysisFlags.None);
        context.EnableConcurrentExecution();
        context.RegisterSyntaxNodeAction(static node =>
        {
            if (!PolicyAnalysis.IsCandidate(node.Node))
            {
                return;
            }

            var found = PolicyAnalysis.Analyze((InvocationExpressionSyntax)node.Node, node.SemanticModel, node.CancellationToken);
            foreach (var diagnostic in found?.Diagnostics ?? Enumerable.Empty<PolicyDiagnostic>())
            {
                node.ReportDiagnostic(diagnostic.ToDiagnostic());
            }
        }, Microsoft.CodeAnalysis.CSharp.SyntaxKind.InvocationExpression);
    }
}
