// Builds results/summary.md from results/raw/. Usage: node tools/summarize.ts
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const spike = join(dirname(fileURLToPath(import.meta.url)), "..");
const raw = join(spike, "results", "raw");

interface Sample {
  scenario: string; combo: string; round: number; items: number; ms: number; nsPerItem: number; longestTaskMs: number; busyMs: number;
  tasks: number; maxBuffered: number; peakHeapGrowth?: number; gcCount?: number; gcMs?: number; longTasks?: number; longTaskMaxMs?: number;
  cpuMs?: number; events?: number; ticks?: number;
}
interface Report {
  engine: string; details: Record<string, unknown>; combos: { key: string; label: string }[]; checks: { combo: string; pass: boolean }[];
  decodeOnly: number[]; samples: Sample[]; retained: { combo: string; bytesPerItem?: number; rssPerItem?: number; buffered: number }[];
}

const read = (file: string) => JSON.parse(readFileSync(join(raw, file), "utf8"));
const median = (xs: number[]) => { const s = [...xs].sort((a, b) => a - b); const n = s.length; return n === 0 ? NaN : n % 2 ? s[(n - 1) / 2]! : (s[n / 2 - 1]! + s[n / 2]!) / 2; };
const range = (xs: number[], d = 0) => `${Math.min(...xs).toFixed(d)}–${Math.max(...xs).toFixed(d)}`;
const sign = (x: number, d = 0) => `${x >= 0 ? "+" : "−"}${Math.abs(x).toFixed(d)}`;

const engines = ["webview2", "node", "webkitgtk"] as const;
const titles: Record<string, string> = { webview2: "WebView2 (Chromium/V8)", node: "Node (V8)", webkitgtk: "WebKitGTK 6.0 (JSC)" };
const lines: string[] = ["# stream-result-cost: summary tables", "", "Generated by `tools/summarize.ts` from `results/raw/`. ns are per item; \"Δ\" is the median over runs of (variant − baseline) per run.", ""];

const runs: Record<string, Report[]> = {};
for (const engine of engines) {
  runs[engine] = readdirSync(raw).filter(f => new RegExp(`^${engine}-\\d+\\.json$`).test(f)).sort().map(read) as Report[];
}

function perRun(reports: Report[], scenario: string, combo: string, field: (s: Sample) => number): number[] {
  return reports.map(r => median(r.samples.filter(s => s.scenario === scenario && s.combo === combo).map(field))).filter(x => !Number.isNaN(x));
}

function timeTable(reports: Report[], scenario: string, extra: "gc" | "peak" | "none"): void {
  const combos = reports[0]!.combos;
  const head = ["Variant", "ns/item", "Δ vs baseline", "longest task ms (max)"];
  if (extra === "gc") head.push("GC count / ms per run (median)");
  if (extra === "peak") head.push("peak heap growth MB (median)");
  if (reports.some(r => r.samples.some(s => s.scenario === scenario && s.longTasks !== undefined))) head.push("long tasks > 50 ms");
  lines.push(`| ${head.join(" | ")} |`, `|${head.map((_, i) => (i === 0 ? "---" : "---:")).join("|")}|`);
  const base = perRun(reports, scenario, "plain", s => s.nsPerItem);
  for (const c of combos) {
    const ns = perRun(reports, scenario, c.key, s => s.nsPerItem);
    if (ns.length === 0) continue;
    const delta = ns.map((x, i) => x - (base[i] ?? NaN));
    const all = reports.flatMap(r => r.samples.filter(s => s.scenario === scenario && s.combo === c.key));
    const row = [c.key === "plain" ? `**${c.label}**` : c.label, `${median(ns).toFixed(0)} [${range(ns)}]`, c.key === "plain" ? "—" : `${sign(median(delta))} [${range(delta)}]`, Math.max(...all.map(s => s.longestTaskMs)).toFixed(2)];
    if (extra === "gc") row.push(`${median(all.map(s => s.gcCount ?? 0)).toFixed(0)} / ${median(all.map(s => s.gcMs ?? 0)).toFixed(1)}`);
    if (extra === "peak") row.push(all.some(s => s.peakHeapGrowth !== undefined) ? (median(all.map(s => s.peakHeapGrowth ?? 0)) / 1e6).toFixed(1) : "n/a");
    if (head.includes("long tasks > 50 ms")) row.push(String(all.reduce((a, s) => a + (s.longTasks ?? 0), 0)));
    lines.push(`| ${row.join(" | ")} |`);
  }
  lines.push("");
}

for (const engine of engines) {
  const reports = runs[engine]!;
  if (reports.length === 0) continue;
  lines.push(`## ${titles[engine]}`, "", `${reports.length} runs. Checks: ${reports.every(r => r.checks.every(c => c.pass)) ? "all passed" : "FAILED"}. Clock resolution ${(Number(reports[0]!.details["clockResolutionMs"]) * 1000).toFixed(1)} µs.`, "");
  const decode = reports.map(r => median(r.decodeOnly));
  lines.push(`Decode alone (JSON.parse + field-by-field rows, no iterator): ${median(decode).toFixed(0)} ns/row [${range(decode)}].`, "");
  for (const [scenario, title, extra] of [
    ["big-100k", "Big loop, 100k items, fast consumer", engine === "node" ? "gc" : "none"],
    ["big-1M", "Big loop, 1M items, fast consumer", engine === "node" ? "gc" : "none"],
    ["slow-microtask", "Slow consumer: `await` a resolved promise per item, 100k items", "peak"],
    ["slow-task", "Slow consumer: one macrotask per item, 20k items (window stays full)", "peak"],
    ["slow-timer", "Slow consumer: `setTimeout(0)` every 100 items, 12k items (1 round)", "peak"],
    ["push-burst", "Push without timers: 60,000 events in batches of 100, one task each (×20,000 = ns per s at 20k events/s)", "none"],
  ] as const) {
    if (!reports.some(r => r.samples.some(s => s.scenario === scenario))) {
      lines.push(`### ${title}`, "", "Skipped on this engine (see RESULTS.md).", "");
      continue;
    }
    lines.push(`### ${title}`, "");
    timeTable(reports, scenario, extra);
  }

  lines.push("### Retained while the app is stalled (window 8 × 1,000, after forced GC)", "");
  const kept = reports.flatMap(r => r.retained);
  const keys = [...new Set(kept.map(k => k.combo))];
  if (kept.some(k => k.bytesPerItem !== undefined)) {
    const base = median(kept.filter(k => k.combo === "plain").map(k => k.bytesPerItem!));
    lines.push("| Variant | bytes per buffered item | Δ vs baseline |", "|---|---:|---:|");
    for (const key of keys) {
      const xs = kept.filter(k => k.combo === key).map(k => k.bytesPerItem!);
      lines.push(`| ${key} | ${median(xs).toFixed(0)} [${range(xs)}] | ${key === "plain" ? "—" : sign(median(xs) - base)} |`);
    }
  } else lines.push("No heap counter: see the RSS table below.");
  lines.push("");

  lines.push("### Subscription push, 20,000 events/s, 3 s, 2 rounds per run", "");
  if (!reports.some(r => r.samples.some(s => s.scenario === "push"))) {
    lines.push("Skipped on this engine: the page is hidden and its timers are throttled.", "");
    continue;
  }
  const pushHead = ["Variant", "page busy ms per s", "Δ ms per s", "ns per event", "events/s", "ticks/s", "longest tick ms"];
  const hasCpu = reports.some(r => r.samples.some(s => s.scenario === "push" && s.cpuMs !== undefined));
  if (hasCpu) pushHead.push("web process CPU ms per s");
  lines.push(`| ${pushHead.join(" | ")} |`, `|${pushHead.map((_, i) => (i === 0 ? "---" : "---:")).join("|")}|`);
  const busyBase = perRun(reports, "push", "plain", s => s.busyMs / (s.ms / 1000));
  for (const c of reports[0]!.combos) {
    const busy = perRun(reports, "push", c.key, s => s.busyMs / (s.ms / 1000));
    const all = reports.flatMap(r => r.samples.filter(s => s.scenario === "push" && s.combo === c.key));
    if (all.length === 0) continue;
    const ns = perRun(reports, "push", c.key, s => s.nsPerItem);
    const row = [c.key, `${median(busy).toFixed(1)} [${range(busy, 1)}]`, c.key === "plain" ? "—" : sign(median(busy.map((x, i) => x - busyBase[i]!)), 1), median(ns).toFixed(0),
      median(all.map(s => s.items / (s.ms / 1000))).toFixed(0), median(all.map(s => (s.ticks ?? 0) / (s.ms / 1000))).toFixed(0), Math.max(...all.map(s => s.longestTaskMs)).toFixed(2)];
    if (hasCpu) row.push(median(all.map(s => (s.cpuMs ?? NaN) / (s.ms / 1000))).toFixed(0));
    lines.push(`| ${row.join(" | ")} |`);
  }
  lines.push("");
}

// Allocation per item (separate processes with a large young generation).
const allocFiles = readdirSync(raw).filter(f => /^alloc-(node|webview2)-\d+\.json$/.test(f)).sort();
if (allocFiles.length > 0) {
  lines.push("## Bytes allocated per item (fast loop; 6 minus 2 batches, 15 reps per run, young generation 64 MB)", "");
  const byEngine: Record<string, { combo: string; bytesPerItem: number; gcInside: number }[][]> = {};
  for (const f of allocFiles) (byEngine[f.split("-")[1]!] ??= []).push(read(f).alloc);
  const keys = [...new Set(Object.values(byEngine).flat(2).map(a => a.combo))];
  const engs = Object.keys(byEngine).sort().reverse();
  lines.push(`| Variant | ${engs.map(e => `${e} bytes/item | Δ`).join(" | ")} |`, `|---|${engs.map(() => "---:|---:").join("|")}|`);
  for (const key of keys) {
    const cells: string[] = [];
    for (const e of engs) {
      const perRunMedians = byEngine[e]!.map(run => median(run.filter(a => a.combo === key).map(a => a.bytesPerItem)));
      const base = byEngine[e]!.map(run => median(run.filter(a => a.combo === "plain").map(a => a.bytesPerItem)));
      cells.push(`${median(perRunMedians).toFixed(0)} [${range(perRunMedians)}]`, key === "plain" ? "—" : sign(median(perRunMedians.map((x, i) => x - base[i]!))));
    }
    lines.push(`| ${key} | ${cells.join(" | ")} |`);
  }
  const gcs = Object.entries(byEngine).map(([e, rs]) => `${e}: ${rs.flat().filter(a => a.gcInside > 0).length} of ${rs.flat().length} samples saw a GC`);
  lines.push("", gcs.join("; ") + " (Node only reports GC entries; WebView2 has no page GC observer).", "");
}

// JSC retained (RSS, fresh process per reading).
const retainedDir = join(raw, "retained");
if (existsSync(retainedDir)) {
  const files = readdirSync(retainedDir).filter(f => f.endsWith(".json"));
  if (files.length > 0) {
    lines.push("## WebKitGTK retained memory (process RSS growth per buffered item, fresh process per reading, no forced GC)", "");
    const rows = files.map(f => JSON.parse(readFileSync(join(retainedDir, f), "utf8")) as { retained: { combo: string; window: number; rssPerItem: number; buffered: number }[] }).flatMap(r => r.retained);
    for (const window of [8, 64]) {
      const at = rows.filter(r => r.window === window);
      if (at.length === 0) continue;
      const base = median(at.filter(r => r.combo === "plain").map(r => r.rssPerItem));
      lines.push(`Window ${window} × 1,000 (${median(at.map(r => r.buffered)).toFixed(0)} items held):`, "", "| Variant | RSS bytes per item | Δ vs baseline | readings |", "|---|---:|---:|---:|");
      for (const key of [...new Set(at.map(r => r.combo))]) {
        const xs = at.filter(r => r.combo === key).map(r => r.rssPerItem);
        lines.push(`| ${key} | ${median(xs).toFixed(0)} [${range(xs)}] | ${key === "plain" ? "—" : sign(median(xs) - base)} | ${xs.length} |`);
      }
      lines.push("");
    }
  }
}

writeFileSync(join(spike, "results", "summary.md"), lines.join("\n"));
console.log(`wrote results/summary.md (${lines.length} lines)`);
