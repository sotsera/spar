# Writes the 20-command sample that the size apps compile: commands written the way an app author would, plus a
# dispatch and JSON writers shaped like the generated ones (no reflection). Two flavours:
#   Result: commands return Task/ValueTask<Result<T, TError>>; the same source compiles against every Result form.
#   Plain:  the same commands without declared errors, returning Task/ValueTask<T>; the baseline.
# Output goes to <variant>/obj/generated/Sample.g.cs and is written only when its content changes.
param(
    [string[]] $Variants = @('Plain', 'Class', 'Struct', 'UnionStruct', 'UnionClass'),
    [ValidateSet('PerCommand', 'OneSwitch')] [string] $DispatchShape = 'PerCommand')

$ErrorActionPreference = 'Stop'
$count = 20

# Commands 15-20 return scalars; the others return records. Value-type T matters for generic sharing.
$scalars = @{
    15 = @{ Type = 'long'; Value = '1234567890123L'; Write = 'writer.WriteStringValue(value.ToString(CultureInfo.InvariantCulture));' }
    16 = @{ Type = 'int'; Value = '42'; Write = 'writer.WriteNumberValue(value);' }
    17 = @{ Type = 'bool'; Value = 'true'; Write = 'writer.WriteBooleanValue(value);' }
    18 = @{ Type = 'Guid'; Value = 'new Guid("0193a8b4-1c2d-7e3f-8a9b-0c1d2e3f4a5b")'; Write = 'writer.WriteStringValue(value.ToString("D"));' }
    19 = @{ Type = 'double'; Value = '0.25'; Write = 'writer.WriteNumberValue(value);' }
    20 = @{ Type = 'string'; Value = '"done"'; Write = 'writer.WriteStringValue(value);' }
}

function Get-ValueType([int] $i)
{
    if ($scalars.ContainsKey($i)) { return $scalars[$i].Type }
    return 'V{0:D2}' -f $i
}

function Get-Sample([bool] $withErrors)
{
    $sb = [System.Text.StringBuilder]::new()
    $null = $sb.AppendLine('// <auto-generated/> by Size/generate.ps1. 20 commands, their types, dispatch and JSON writers.')
    $null = $sb.AppendLine('#nullable enable')
    $null = $sb.AppendLine('using System.Buffers;')
    $null = $sb.AppendLine('using System.Globalization;')
    $null = $sb.AppendLine('using System.Text.Json;')
    if ($withErrors) { $null = $sb.AppendLine('using Spar;') }
    $null = $sb.AppendLine('')
    $null = $sb.AppendLine('namespace Sample;')
    $null = $sb.AppendLine('')
    $null = $sb.AppendLine('public sealed record Req(string Id, bool Fail, bool Yield);')
    for ($i = 1; $i -le $count; $i++)
    {
        $n = '{0:D2}' -f $i
        if (-not $scalars.ContainsKey($i))
        {
            $null = $sb.AppendLine("public sealed record V$n(string Name, long Count, IReadOnlyList<string> Tags);")
        }
        if ($withErrors)
        {
            $null = $sb.AppendLine("public closed record E$n")
            $null = $sb.AppendLine('{')
            $null = $sb.AppendLine("    public sealed record NotFound(string Id) : E$n;")
            $null = $sb.AppendLine("    public sealed record Conflict(string Id, long Version) : E$n;")
            $null = $sb.AppendLine('}')
        }
    }

    # The service: what the app author writes.
    $null = $sb.AppendLine('')
    $null = $sb.AppendLine('public sealed class Service')
    $null = $sb.AppendLine('{')
    $null = $sb.AppendLine('    private static readonly string[] s_tags = ["a", "b"];')
    for ($i = 1; $i -le $count; $i++)
    {
        $n = '{0:D2}' -f $i
        $t = Get-ValueType $i
        $value = if ($scalars.ContainsKey($i)) { $scalars[$i].Value } else { "new V$n(req.Id, $i, s_tags)" }
        $task = if ($i % 2 -eq 1) { 'Task' } else { 'ValueTask' }
        $returnType = if ($withErrors) { "$task<Result<$t, E$n>>" } else { "$task<$t>" }
        $null = $sb.AppendLine("    public async $returnType C${n}Async(Req req)")
        $null = $sb.AppendLine('    {')
        $null = $sb.AppendLine('        if (req.Yield)')
        $null = $sb.AppendLine('        {')
        $null = $sb.AppendLine('            await Task.Yield();')
        $null = $sb.AppendLine('        }')
        if ($withErrors)
        {
            $null = $sb.AppendLine('        if (req.Fail)')
            $null = $sb.AppendLine('        {')
            $null = $sb.AppendLine("            return req.Id.Length % 2 == 0 ? new E$n.NotFound(req.Id) : new E$n.Conflict(req.Id, $i);")
            $null = $sb.AppendLine('        }')
        }
        $null = $sb.AppendLine("        return $value;")
        $null = $sb.AppendLine('    }')
    }
    $null = $sb.AppendLine('}')

    # The dispatch and writers: what the generator would emit.
    $null = $sb.AppendLine('')
    $null = $sb.AppendLine('public static class Dispatch')
    $null = $sb.AppendLine('{')
    $null = $sb.AppendLine('    public const int CommandCount = 20;')
    $null = $sb.AppendLine('')
    if ($DispatchShape -eq 'OneSwitch')
    {
        # One async method awaiting every command: its state machine holds an awaiter field per result type.
        $null = $sb.AppendLine('    public static async ValueTask RunAsync(Service service, int command, Req req, ArrayBufferWriter<byte> buffer)')
        $null = $sb.AppendLine('    {')
        $null = $sb.AppendLine('        switch (command)')
        $null = $sb.AppendLine('        {')
        for ($i = 1; $i -le $count; $i++)
        {
            $n = '{0:D2}' -f $i
            $null = $sb.AppendLine("            case ${i}:")
            $null = $sb.AppendLine('            {')
            $null = $sb.AppendLine("                var result = await service.C${n}Async(req);")
            $null = $sb.AppendLine('                var writer = Writer(buffer);')
            $null = $sb.AppendLine("                WriteResult$n(writer, result);")
            $null = $sb.AppendLine('                writer.Flush();')
            $null = $sb.AppendLine('                return;')
            $null = $sb.AppendLine('            }')
        }
        $null = $sb.AppendLine('            default:')
        $null = $sb.AppendLine('                throw new ArgumentOutOfRangeException(nameof(command));')
        $null = $sb.AppendLine('        }')
        $null = $sb.AppendLine('    }')
    }
    else
    {
        # One small async method per command, selected by a non-async switch.
        $null = $sb.AppendLine('    public static ValueTask RunAsync(Service service, int command, Req req, ArrayBufferWriter<byte> buffer) =>')
        $null = $sb.AppendLine('        command switch')
        $null = $sb.AppendLine('        {')
        for ($i = 1; $i -le $count; $i++)
        {
            $n = '{0:D2}' -f $i
            $null = $sb.AppendLine("            $i => Run${n}Async(service, req, buffer),")
        }
        $null = $sb.AppendLine('            _ => throw new ArgumentOutOfRangeException(nameof(command)),')
        $null = $sb.AppendLine('        };')
        for ($i = 1; $i -le $count; $i++)
        {
            $n = '{0:D2}' -f $i
            $null = $sb.AppendLine('')
            $null = $sb.AppendLine("    private static async ValueTask Run${n}Async(Service service, Req req, ArrayBufferWriter<byte> buffer)")
            $null = $sb.AppendLine('    {')
            $null = $sb.AppendLine("        var result = await service.C${n}Async(req);")
            $null = $sb.AppendLine('        var writer = Writer(buffer);')
            $null = $sb.AppendLine("        WriteResult$n(writer, result);")
            $null = $sb.AppendLine('        writer.Flush();')
            $null = $sb.AppendLine('    }')
        }
    }
    $null = $sb.AppendLine('')
    $null = $sb.AppendLine('    [ThreadStatic]')
    $null = $sb.AppendLine('    private static Utf8JsonWriter? t_writer;')
    $null = $sb.AppendLine('')
    $null = $sb.AppendLine('    // One pooled writer per thread, reset onto the call''s buffer, as the bridge does.')
    $null = $sb.AppendLine('    private static Utf8JsonWriter Writer(ArrayBufferWriter<byte> buffer)')
    $null = $sb.AppendLine('    {')
    $null = $sb.AppendLine('        var writer = t_writer ??= new Utf8JsonWriter(buffer);')
    $null = $sb.AppendLine('        writer.Reset(buffer);')
    $null = $sb.AppendLine('        return writer;')
    $null = $sb.AppendLine('    }')
    for ($i = 1; $i -le $count; $i++)
    {
        $n = '{0:D2}' -f $i
        $t = Get-ValueType $i
        $null = $sb.AppendLine('')
        if ($withErrors)
        {
            $null = $sb.AppendLine("    private static void WriteResult$n(Utf8JsonWriter writer, Result<$t, E$n> result)")
            $null = $sb.AppendLine('    {')
            $null = $sb.AppendLine('        writer.WriteStartObject();')
            $null = $sb.AppendLine('        if (result.TryGetError(out var error))')
            $null = $sb.AppendLine('        {')
            $null = $sb.AppendLine('            writer.WriteBoolean("ok"u8, false);')
            $null = $sb.AppendLine('            writer.WritePropertyName("error"u8);')
            $null = $sb.AppendLine("            WriteE$n(writer, error);")
            $null = $sb.AppendLine('        }')
            $null = $sb.AppendLine('        else')
            $null = $sb.AppendLine('        {')
            $null = $sb.AppendLine('            writer.WriteBoolean("ok"u8, true);')
            $null = $sb.AppendLine('            writer.WritePropertyName("value"u8);')
            $null = $sb.AppendLine("            WriteValue$n(writer, result.Value);")
            $null = $sb.AppendLine('        }')
            $null = $sb.AppendLine('        writer.WriteEndObject();')
            $null = $sb.AppendLine('    }')
            $null = $sb.AppendLine('')
            $null = $sb.AppendLine("    private static void WriteE$n(Utf8JsonWriter writer, E$n error)")
            $null = $sb.AppendLine('    {')
            $null = $sb.AppendLine('        writer.WriteStartObject();')
            $null = $sb.AppendLine('        switch (error)')
            $null = $sb.AppendLine('        {')
            $null = $sb.AppendLine("            case E$n.NotFound notFound:")
            $null = $sb.AppendLine('                writer.WriteString("code"u8, "notFound"u8);')
            $null = $sb.AppendLine('                writer.WriteString("id"u8, notFound.Id);')
            $null = $sb.AppendLine('                break;')
            $null = $sb.AppendLine("            case E$n.Conflict conflict:")
            $null = $sb.AppendLine('                writer.WriteString("code"u8, "conflict"u8);')
            $null = $sb.AppendLine('                writer.WriteString("id"u8, conflict.Id);')
            $null = $sb.AppendLine('                writer.WriteString("version"u8, conflict.Version.ToString(CultureInfo.InvariantCulture));')
            $null = $sb.AppendLine('                break;')
            $null = $sb.AppendLine('        }')
            $null = $sb.AppendLine('        writer.WriteEndObject();')
            $null = $sb.AppendLine('    }')
        }
        else
        {
            $null = $sb.AppendLine("    private static void WriteResult$n(Utf8JsonWriter writer, $t value)")
            $null = $sb.AppendLine('    {')
            $null = $sb.AppendLine('        writer.WriteStartObject();')
            $null = $sb.AppendLine('        writer.WriteBoolean("ok"u8, true);')
            $null = $sb.AppendLine('        writer.WritePropertyName("value"u8);')
            $null = $sb.AppendLine("        WriteValue$n(writer, value);")
            $null = $sb.AppendLine('        writer.WriteEndObject();')
            $null = $sb.AppendLine('    }')
        }
        $null = $sb.AppendLine('')
        $null = $sb.AppendLine("    private static void WriteValue$n(Utf8JsonWriter writer, $t value)")
        $null = $sb.AppendLine('    {')
        if ($scalars.ContainsKey($i))
        {
            $null = $sb.AppendLine("        $($scalars[$i].Write)")
        }
        else
        {
            $null = $sb.AppendLine('        writer.WriteStartObject();')
            $null = $sb.AppendLine('        writer.WriteString("name"u8, value.Name);')
            $null = $sb.AppendLine('        writer.WriteString("count"u8, value.Count.ToString(CultureInfo.InvariantCulture));')
            $null = $sb.AppendLine('        writer.WriteStartArray("tags"u8);')
            $null = $sb.AppendLine('        foreach (var tag in value.Tags)')
            $null = $sb.AppendLine('        {')
            $null = $sb.AppendLine('            writer.WriteStringValue(tag);')
            $null = $sb.AppendLine('        }')
            $null = $sb.AppendLine('        writer.WriteEndArray();')
            $null = $sb.AppendLine('        writer.WriteEndObject();')
        }
        $null = $sb.AppendLine('    }')
    }
    $null = $sb.AppendLine('}')
    return $sb.ToString()
}

$samples = @{ $true = (Get-Sample $true); $false = (Get-Sample $false) }
foreach ($variant in $Variants)
{
    $content = $samples[$variant -ne 'Plain']
    $folder = Join-Path $PSScriptRoot "$variant/obj/generated"
    $path = Join-Path $folder 'Sample.g.cs'
    New-Item -ItemType Directory -Force $folder | Out-Null
    if ((Test-Path $path) -and ((Get-Content $path -Raw) -eq $content))
    {
        continue
    }

    Set-Content -Path $path -Value $content -NoNewline -Encoding utf8
    Write-Host "wrote $variant/obj/generated/Sample.g.cs"
}
