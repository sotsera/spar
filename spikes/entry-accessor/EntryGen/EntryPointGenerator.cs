using System.Threading;
using Microsoft.CodeAnalysis;

namespace EntryGen;

/// <summary>
/// In the Test variant only, makes the app's <c>Program</c> public and implements <c>Spar.ISparEntryPoint</c> on it,
/// calling the compiler's top-level entry method through an unsafe accessor. A test then writes
/// <c>SparTestApp.StartAsync&lt;Program&gt;()</c>: no reflection, no hand-written accessor, and NativeAOT-safe.
/// The entry method's metadata name comes from the compilation, never from a guess.
/// </summary>
[Generator]
public sealed class EntryPointGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor NotTopLevel = new(
        "SPIKE001",
        "Program.cs must use top-level statements",
        "The test host runs Program.cs, which must be top-level statements (one Create, one Run); the entry point is '{0}'",
        "Spar",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor NotReturningRun = new(
        "SPIKE002",
        "Program.cs must return app.Run()",
        "The test host needs the top-level statements to end with 'return app.Run();' (an int); they return '{0}'",
        "Spar",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var isTest = context.AnalyzerConfigOptionsProvider.Select(static (options, _) =>
            options.GlobalOptions.TryGetValue("build_property.SparVariant", out var variant) && variant == "Test");
        var entry = context.CompilationProvider.Select(static (compilation, cancellationToken) => Describe(compilation, cancellationToken));

        context.RegisterSourceOutput(entry.Combine(isTest), static (output, pair) =>
        {
            var (info, test) = pair;
            if (!test || info is null)
            {
                return;
            }

            if (!info.TopLevel)
            {
                output.ReportDiagnostic(Diagnostic.Create(NotTopLevel, info.Location, info.Display));
                return;
            }

            if (info.ReturnType != "int")
            {
                output.ReportDiagnostic(Diagnostic.Create(NotReturningRun, info.Location, info.ReturnType));
                return;
            }

            output.AddSource("Spar.TestEntryPoint.g.cs", Emit(info));
        });
    }

    private static EntryInfo? Describe(Compilation compilation, CancellationToken cancellationToken)
    {
        var method = compilation.GetEntryPoint(cancellationToken);
        if (method is null)
        {
            return null;
        }

        var type = method.ContainingType;
        var topLevel = method.Name == WellKnownMemberNames.TopLevelStatementsEntryPointMethodName;
        var location = type.Locations.Length > 0 ? type.Locations[0] : Location.None;
        return new EntryInfo(
            method.ToDisplayString(),
            type.ContainingNamespace.IsGlobalNamespace ? null : type.ContainingNamespace.ToDisplayString(),
            type.Name,
            method.Name,
            method.ReturnType.ToDisplayString(),
            topLevel,
            location);
    }

    private static string Emit(EntryInfo info)
    {
        var open = info.Namespace is null ? "" : $"namespace {info.Namespace};\n\n";
        return $$"""
            // <auto-generated/> Spar, Test variant only.
            #nullable enable
            {{open}}public partial class {{info.TypeName}} : global::Spar.ISparEntryPoint
            {
                static int global::Spar.ISparEntryPoint.Run(string[] args) => SparEntry(null, args);

                [global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.StaticMethod, Name = "{{info.MethodName}}")]
                private static extern int SparEntry({{info.TypeName}}? program, string[] args);
            }

            """;
    }

    private sealed class EntryInfo(
        string display, string? @namespace, string typeName, string methodName, string returnType, bool topLevel, Location location)
    {
        public string Display { get; } = display;

        public string? Namespace { get; } = @namespace;

        public string TypeName { get; } = typeName;

        public string MethodName { get; } = methodName;

        public string ReturnType { get; } = returnType;

        public bool TopLevel { get; } = topLevel;

        public Location Location { get; } = location;
    }
}
