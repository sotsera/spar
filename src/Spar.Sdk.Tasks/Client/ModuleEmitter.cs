using System.Text.RegularExpressions;
using Spar.Generator;

namespace Spar.Sdk.Tasks.Client;

/// <summary>
/// The <c>.js</c> of each module: a reader and a writer per record, a reader per error type, a decoder per command, and
/// the contract's object, whose functions hand the SDK's <c>invoke</c> the encoder of the request. Every value is
/// read and written field by field through the SDK's <c>wire</c> module (plan section 2: a parsed <c>__proto__</c>
/// key must never reach a copy), so no SDK logic is copied here.
/// </summary>
internal static partial class ModuleEmitter
{
    public static string Contract(ClientLayout layout, ClientContract contract)
    {
        var model = contract.Model;
        var js = new TypeScriptWriter()
            .Line($"// Generated by Spar from {contract.SourceFile}. Do not edit.")
            .Line("import { invoke, unknownErrorCase } from \"./sdk/sdk.js\";")
            .Line("import * as wire from \"./sdk/wire.js\";");

        var imported = layout.Imported(contract).SelectMany(Functions).ToList();
        if (imported.Count > 0)
        {
            js.Line($"import {{ {string.Join(", ", imported)} }} from \"./shared.js\";");
        }

        foreach (var type in layout.Own(contract))
        {
            Type(js, layout, type, exported: false);
        }

        js.Line();
        js.Line("const noValue = () => undefined;");
        js.Line("const noErrors = () => unknownErrorCase;");
        foreach (var command in model.Commands)
        {
            js.Line();
            Decoder(js, layout, command);
        }

        js.Line();
        ContractObject(js, layout, contract);
        return js.ToString();
    }

    public static string Shared(ClientLayout layout)
    {
        var js = new TypeScriptWriter()
            .Line("// Generated by Spar: the types more than one contract uses. Do not edit.")
            .Line("import { unknownErrorCase } from \"./sdk/sdk.js\";")
            .Line("import * as wire from \"./sdk/wire.js\";");
        foreach (var type in layout.Shared)
        {
            Type(js, layout, type, exported: true);
        }

        return js.ToString();
    }

    public static string Spar(string fingerprint) => new TypeScriptWriter()
        .Line("// Generated by Spar. Do not edit.")
        .Line()
        .Line("/** The contracts' fingerprint this page was built against; the host compares it once, when the page opens. */")
        .Line($"export const fingerprint = {TypeScriptNames.Literal(fingerprint)};")
        .ToString();

    /// <summary>Plain identifiers, which can be written as property names and read with a dot.</summary>
    public static bool IsIdentifier(string name) => Identifier().IsMatch(name) && !TypeScriptNames.IsReserved(name);

    private static IEnumerable<string> Functions(ClientType type) =>
        type.Record is null
            ? [ClientNames.Reader(type.Name)]
            : [ClientNames.Reader(type.Name), ClientNames.Writer(type.Name)];

    private static void Type(TypeScriptWriter js, ClientLayout layout, ClientType type, bool exported)
    {
        var export = exported ? "export " : "";
        if (type.Record is { } record)
        {
            js.Line();
            RecordReader(js, layout, type, record, export);
            js.Line();
            RecordWriter(js, layout, type, record, export);
            return;
        }

        js.Line();
        ErrorReader(js, layout, type, type.Error!, export);
    }

    private static void RecordReader(TypeScriptWriter js, ClientLayout layout, ClientType type, RecordModel record, string export)
    {
        js.Open($"{export}function {ClientNames.Reader(type.Name)}(value) {{")
            .Line("const object = wire.readObject(value);");
        ObjectLiteral(js, layout, record.Properties, "return {", "};");
        js.Close();
    }

    private static void RecordWriter(TypeScriptWriter js, ClientLayout layout, ClientType type, RecordModel record, string export)
    {
        js.Open($"{export}function {ClientNames.Writer(type.Name)}(value) {{");
        if (record.Properties.Length == 0)
        {
            js.Line("return \"{}\";").Close();
            return;
        }

        js.Open("return wire.writeObject([");
        foreach (var property in record.Properties)
        {
            var name = TypeScriptNames.Literal(property.JsonName);
            js.Line($"wire.member({name}, {Write(layout, property.Type, Access("value", property.JsonName), 0)}),");
        }

        js.Close("]);").Close();
    }

    private static void ErrorReader(TypeScriptWriter js, ClientLayout layout, ClientType type, ErrorModel error, string export)
    {
        js.Open($"{export}function {ClientNames.Reader(type.Name)}(code, payload) {{").Open("switch (code) {");
        foreach (var @case in error.Cases)
        {
            if (@case.Properties.Length == 0)
            {
                js.Open($"case {TypeScriptNames.Literal(@case.Code)}:").Line("return undefined;").Outdent();
                continue;
            }

            // Each case is a block of its own, so its locals do not clash with the next case's.
            js.Open($"case {TypeScriptNames.Literal(@case.Code)}: {{").Line("const object = payload;");
            ObjectLiteral(js, layout, @case.Properties, "return {", "};");
            js.Close();
        }

        js.Open("default:").Line("return unknownErrorCase;").Outdent();
        js.Close().Close();
    }

    /// <summary>A new object, one property at a time from <c>object</c>: never a copy of the parsed one.</summary>
    private static void ObjectLiteral(TypeScriptWriter js, ClientLayout layout, EquatableArray<PropertyModel> properties, string open, string close)
    {
        js.Open(open);
        foreach (var property in properties)
        {
            var value = $"wire.field(object, {TypeScriptNames.Literal(property.JsonName)})";
            js.Line($"{LiteralKey(property.JsonName)}: {Read(layout, property.Type, value, 0)},");
        }

        js.Close(close);
    }

    private static void Decoder(TypeScriptWriter js, ClientLayout layout, CommandModel command)
    {
        var value = command.Value is null ? "noValue" : $"json => {Read(layout, command.Value, "JSON.parse(json)", 0)}";
        var error = command.ErrorKey is null ? "noErrors" : ClientNames.Reader(layout.Type(command.ErrorKey).Name);
        js.Line($"const {ClientNames.Decoder(command.WireName)} = {{ value: {value}, error: {error} }};");
    }

    private static void ContractObject(TypeScriptWriter js, ClientLayout layout, ClientContract contract)
    {
        var model = contract.Model;
        var wireName = $"Wire name: {model.WireName}.";
        var summary = contract.Docs.Type(model.CSharp);
        js.Doc(summary is null ? wireName : $"{summary} {wireName}").Open($"export const {model.WireName} = Object.freeze({{");

        var first = true;
        foreach (var command in model.Commands)
        {
            if (!first)
            {
                js.Line();
            }

            first = false;
            var contractName = TypeScriptNames.Literal(model.WireName);
            var commandName = TypeScriptNames.Literal(command.WireName);
            var decoder = ClientNames.Decoder(command.WireName);
            string function;
            if (command.Request is null)
            {
                function = $"options => invoke({contractName}, {commandName}, () => \"\", {decoder}, options)";
            }
            else
            {
                var request = DeclarationEmitter.RequestName(command);
                var encode = Write(layout, command.Request, request, 0);
                function = $"({request}, options) => invoke({contractName}, {commandName}, () => {encode}, {decoder}, options)";
            }

            js.Doc(contract.Docs.Method(model.CSharp, command.MethodName)).Line($"{LiteralKey(command.WireName)}: {function},");
        }

        js.Close("});");
    }

    /// <summary>The expression that reads <paramref name="value"/> as <paramref name="type"/>.</summary>
    private static string Read(ClientLayout layout, TypeRef type, string value, int depth) => type.Kind switch
    {
        WireKind.List => $"wire.readList({value}, {Reader(layout, type.Element!, depth + 1)})",
        WireKind.Nullable => $"wire.readNullable({value}, {Reader(layout, type.Element!, depth + 1)})",
        _ => $"{Reader(layout, type, depth)}({value})",
    };

    /// <summary>A function that reads one value of <paramref name="type"/>.</summary>
    private static string Reader(ClientLayout layout, TypeRef type, int depth) => type.Kind switch
    {
        WireKind.String or WireKind.Guid or WireKind.DateTimeOffset => "wire.readString",
        WireKind.Boolean => "wire.readBoolean",
        WireKind.Int32 => "wire.readInt32",
        WireKind.Int64 => "wire.readInt64",
        WireKind.Double => "wire.readDouble",
        WireKind.Record => ClientNames.Reader(layout.Type(type.Key).Name),
        _ => $"{Item(depth)} => {Read(layout, type, Item(depth), depth)}",
    };

    /// <summary>The expression that writes <paramref name="value"/> as <paramref name="type"/>'s JSON.</summary>
    private static string Write(ClientLayout layout, TypeRef type, string value, int depth) => type.Kind switch
    {
        WireKind.List => $"wire.writeList({value}, {Writer(layout, type.Element!, depth + 1)})",
        WireKind.Nullable => $"wire.writeNullable({value}, {Writer(layout, type.Element!, depth + 1)})",
        _ => $"{Writer(layout, type, depth)}({value})",
    };

    private static string Writer(ClientLayout layout, TypeRef type, int depth) => type.Kind switch
    {
        WireKind.String or WireKind.Guid or WireKind.DateTimeOffset => "wire.writeString",
        WireKind.Boolean => "wire.writeBoolean",
        WireKind.Int32 => "wire.writeInt32",
        WireKind.Int64 => "wire.writeInt64",
        WireKind.Double => "wire.writeDouble",
        WireKind.Record => ClientNames.Writer(layout.Type(type.Key).Name),
        _ => $"{Item(depth)} => {Write(layout, type, Item(depth), depth)}",
    };

    private static string Item(int depth) => depth <= 1 ? "item" : $"item{depth}";

    private static string Access(string value, string name) => IsIdentifier(name) ? $"{value}.{name}" : $"{value}[{TypeScriptNames.Literal(name)}]";

    /// <summary>A key in an object literal; <c>__proto__</c> is computed, or it would set the prototype instead.</summary>
    private static string LiteralKey(string name)
    {
        if (name == "__proto__")
        {
            return $"[{TypeScriptNames.Literal(name)}]";
        }

        return IsIdentifier(name) ? name : TypeScriptNames.Literal(name);
    }

    [GeneratedRegex("^[A-Za-z_$][A-Za-z0-9_$]*$")]
    private static partial Regex Identifier();
}
