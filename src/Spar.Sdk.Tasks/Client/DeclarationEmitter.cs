using Spar.Generator;

namespace Spar.Sdk.Tasks.Client;

/// <summary>
/// The <c>.d.ts</c> of each module (<c>docs/app-model.md</c> section 5): DTOs as <c>readonly</c> interfaces, each error
/// type as an interface map from case to payload, and one object per contract with a property per command.
/// </summary>
internal static class DeclarationEmitter
{
    public static string Contract(ClientLayout layout, ClientContract contract)
    {
        var ts = new TypeScriptWriter()
            .Line($"// Generated by Spar from {contract.SourceFile}. Do not edit.")
            // By package name, as app code writes it; TypeScript resolves the package's own name through its exports.
            .Line($"import type {{ {string.Join(", ", TypeScriptNames.SdkImports)} }} from \"@spar/app/sdk\";");

        var imported = layout.Imported(contract).Select(t => t.Name).ToList();
        if (imported.Count > 0)
        {
            var names = string.Join(", ", imported);
            ts.Line($"import type {{ {names} }} from \"./shared.js\";")
                .Line()
                .Line($"export type {{ {names} }} from \"./shared.js\";");
        }

        foreach (var type in layout.Own(contract))
        {
            ts.Line();
            Type(ts, layout, type, contract.Docs);
        }

        ts.Line();
        ContractObject(ts, layout, contract);
        return ts.ToString();
    }

    public static string Shared(ClientLayout layout)
    {
        var ts = new TypeScriptWriter().Line("// Generated by Spar: the types more than one contract uses. Do not edit.");
        foreach (var type in layout.Shared)
        {
            var docs = layout.Contracts.First(c => c.Model.Records.Any(r => r.Key == type.Key) || c.Model.Errors.Any(e => e.Key == type.Key)).Docs;
            ts.Line();
            Type(ts, layout, type, docs);
        }

        return ts.ToString();
    }

    public static string Spar() => new TypeScriptWriter()
        .Line("// Generated by Spar. Do not edit.")
        .Line()
        .Line("/** The contracts' fingerprint this page was built against; the host compares it once, when the page opens. */")
        .Line("export declare const fingerprint: string;")
        .ToString();

    private static void Type(TypeScriptWriter ts, ClientLayout layout, ClientType type, ClientDocs docs)
    {
        if (type.Record is { } record)
        {
            ts.Doc(docs.Type(record.CSharp)).Open($"export interface {type.Name} {{");
            Properties(ts, layout, record.CSharp, record.Properties, docs);
            ts.Close();
            return;
        }

        var error = type.Error!;
        var cSharpName = $"(C# `{type.Name}`)";
        var summary = docs.Type(error.CSharp);
        ts.Doc(summary is null ? cSharpName : $"{summary} {cSharpName}").Open($"export interface {type.Name} {{");
        var first = true;
        foreach (var @case in error.Cases)
        {
            if (!first)
            {
                ts.Line();
            }

            first = false;
            ts.Doc(docs.Type(@case.CSharp));
            if (@case.Properties.Length == 0)
            {
                ts.Line($"readonly {Key(@case.Code)}: undefined;");
                continue;
            }

            ts.Open($"readonly {Key(@case.Code)}: {{");
            Properties(ts, layout, @case.CSharp, @case.Properties, docs);
            ts.Close("};");
        }

        ts.Close();
    }

    private static void Properties(TypeScriptWriter ts, ClientLayout layout, string owner, EquatableArray<PropertyModel> properties, ClientDocs docs)
    {
        foreach (var property in properties)
        {
            ts.Doc(docs.Parameter(owner, property.Name)).Line($"readonly {Key(property.JsonName)}: {TypeOf(layout, property.Type)};");
        }
    }

    private static void ContractObject(TypeScriptWriter ts, ClientLayout layout, ClientContract contract)
    {
        var model = contract.Model;
        var wireName = $"Wire name: {model.WireName}.";
        var summary = contract.Docs.Type(model.CSharp);
        ts.Doc(summary is null ? wireName : $"{summary} {wireName}").Open($"export declare const {model.WireName}: {{");

        var first = true;
        foreach (var command in model.Commands)
        {
            if (!first)
            {
                ts.Line();
            }

            first = false;
            var parameters = command.Request is null
                ? "options?: CallOptions"
                : $"{RequestName(command)}: {TypeOf(layout, command.Request)}, options?: CallOptions";
            ts.Doc(contract.Docs.Method(model.CSharp, command.MethodName))
                .Line($"readonly {Key(command.WireName)}: ({parameters}) => {CallType(layout, command)};");
        }

        ts.Close("};");
    }

    /// <summary>A record request is <c>request</c>, as in the app model; a scalar keeps its C# parameter name.</summary>
    public static string RequestName(CommandModel command) =>
        command.Request?.Kind == WireKind.Record ? "request" : TypeScriptNames.Parameter(command.RequestName ?? "request");

    private static string CallType(ClientLayout layout, CommandModel command)
    {
        var value = command.Value is null ? "void" : TypeOf(layout, command.Value);
        return command.ErrorKey is null ? $"Call<{value}>" : $"Call<{value}, {layout.Type(command.ErrorKey).Name}>";
    }

    /// <summary>The TypeScript spelling of a wire type (plan section 2, the wire-rules table).</summary>
    public static string TypeOf(ClientLayout layout, TypeRef type) => type.Kind switch
    {
        WireKind.String or WireKind.Guid or WireKind.DateTimeOffset => "string",
        WireKind.Boolean => "boolean",
        WireKind.Int32 or WireKind.Double => "number",
        WireKind.Int64 => "bigint",
        WireKind.List => $"readonly {Parenthesized(TypeOf(layout, type.Element!))}[]",
        WireKind.Nullable => $"{TypeOf(layout, type.Element!)} | null",
        WireKind.Record => layout.Type(type.Key).Name,
        _ => throw new InvalidOperationException($"No TypeScript spelling for wire kind {type.Kind}."),
    };

    /// <summary>A property name as written in an interface: plain when it is an identifier, quoted otherwise.</summary>
    public static string Key(string name) => ModuleEmitter.IsIdentifier(name) ? name : TypeScriptNames.Literal(name);

    private static string Parenthesized(string type) => type.Contains(' ', StringComparison.Ordinal) ? $"({type})" : type;
}
