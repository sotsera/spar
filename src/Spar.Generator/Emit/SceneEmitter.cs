using System.Collections.Generic;
using System.Text;

namespace Spar.Generator;

/// <summary>
/// <c>Spar.Scenes.g.cs</c> in a test project that references Spar.Testing (decision "M2c's decide-first questions",
/// items 1 and 2): a module initializer that registers each scene with <c>SparScenes</c> and then lets <c>spar snap</c>
/// take over the process when it asked (before the test framework's entry point runs); and, when the project uses
/// xUnit, one window test per scene, so a broken scene fails <c>dotnet test</c>. xUnit's NativeAOT lane finds its tests
/// with a source generator of its own, which does not see these, so they run in the CoreCLR lane.
/// </summary>
internal static class SceneEmitter
{
    public static string Emit(IEnumerable<SceneModel> found, bool xunit)
    {
        var scenes = new List<SceneModel>(found);
        var code = new StringBuilder();
        code.Append("// <auto-generated/>\n");
        code.Append("// The test project's scenes ([SparScene] methods), registered for spar snap and its generated tests.\n");
        code.Append("#nullable enable\n\n");
        code.Append("namespace Spar.Generated\n{\n");
        code.Append("    internal static class SparSceneRegistration\n    {\n");
        code.Append("        [global::System.Runtime.CompilerServices.ModuleInitializer]\n");
        code.Append("        internal static void Register()\n        {\n");
        foreach (var scene in scenes)
        {
            code.Append("            global::Spar.Testing.SparScenes.Register(\"").Append(scene.Name).Append("\", ").Append(scene.Method).Append(");\n");
        }

        code.Append("            global::Spar.Testing.SparScenes.RunIfAsked();\n");
        code.Append("        }\n    }\n");
        if (xunit && scenes.Count > 0)
        {
            code.Append('\n');
            code.Append("    /// <summary>Each scene as a window test: it runs the scene and its capture, writing nothing.</summary>\n");
            code.Append("    [global::Xunit.Trait(\"Surface\", \"Window\")]\n");
            code.Append("    public sealed class SparSceneTests\n    {\n");
            var first = true;
            foreach (var scene in scenes)
            {
                if (!first)
                {
                    code.Append('\n');
                }

                first = false;
                code.Append("        [global::Xunit.Fact]\n");
                code.Append("        [global::Xunit.Trait(\"SparScene\", \"").Append(scene.Name).Append("\")]\n");
                code.Append("        public global::System.Threading.Tasks.Task ").Append(scene.TestName).Append("() =>\n");
                code.Append("            global::Spar.Testing.SparScenes.RunAsTestAsync(\"").Append(scene.Name)
                    .Append("\", global::Xunit.TestContext.Current.CancellationToken);\n");
            }

            code.Append("    }\n");
        }

        code.Append("}\n");
        return code.ToString();
    }
}
