using System.Linq;

namespace Spar.Generator.Emit;

/// <summary>
/// The build's identity (decision "M1d's decide-first questions"; plan, M1d step 6): <c>SparBuildIdentity.Block</c>, one
/// marked block of printable ASCII in the app's image, <c>[spar-build-identity/1 variant=… revision=… dirty=…
/// fingerprint=…]</c>, which the catalog hands the host for its first log line and <c>spar doctor</c> reads from the
/// file without running it (the format is <c>Spar.Runtime.BuildIdentity</c>'s). A UTF-8 literal, so the bytes sit in the
/// image as they are, in the IL assembly and in a NativeAOT executable alike.
/// <para>
/// The values come from the build through <c>CompilerVisibleProperty</c>: <c>SparVariant</c>, <c>SparBuildRevision</c>
/// (the .NET SDK's <c>SourceRevisionId</c>) and <c>SparBuildDirty</c> (git's status of the work tree), each kept to the
/// characters the format allows; the fingerprint is the catalog's own. Its own file, apart from
/// <c>Spar.Contracts.g.cs</c>: a commit or the first edit after one changes the identity, never the contracts' shape,
/// so Hot Reload's restart rule (<see cref="ShapeEmitter"/>) does not see it.
/// </para>
/// </summary>
internal static class IdentityEmitter
{
    /// <summary>The block's start, the runtime's <c>BuildIdentity.Marker</c>.</summary>
    public const string Marker = "[spar-build-identity/1 ";

    public static string Emit(IdentityModel identity, string fingerprint)
    {
        var dirty = identity.Dirty.Trim().ToLowerInvariant() is "true" or "false" ? identity.Dirty.Trim().ToLowerInvariant() : "";
        var block = $"{Marker}variant={Clean(identity.Variant)} revision={Clean(identity.Revision)} dirty={dirty} fingerprint={Clean(fingerprint)}]";
        return new CodeWriter()
            .Line("// <auto-generated/> Spar: the build's identity, which the host logs and spar doctor reads from the file.")
            .Line()
            .Open("namespace Spar.Generated")
            .Open("internal static class SparBuildIdentity")
            .Line("/// <summary>The variant, the git revision, whether the work tree had uncommitted changes, and the contracts' fingerprint.</summary>")
            .Line($"public static global::System.ReadOnlySpan<byte> Block => \"{block}\"u8;")
            .Close()
            .Close()
            .ToString();
    }

    /// <summary>A value with only ASCII letters, digits, <c>.</c>, <c>_</c> and <c>-</c>, or empty when it has anything else.</summary>
    internal static string Clean(string value)
    {
        var trimmed = value.Trim();
        var allowed = trimmed.Length <= 128 && trimmed.All(c =>
            c is (>= 'a' and <= 'z') or (>= 'A' and <= 'Z') or (>= '0' and <= '9') or '.' or '_' or '-');
        return allowed ? trimmed : "";
    }
}

/// <summary>The identity's values from the build, as MSBuild passed them; empty when a property is not set.</summary>
internal sealed record IdentityModel(string Variant, string Revision, string Dirty);
