using System.Linq;
using System.Security.Cryptography;
using System.Text;

namespace Spar.Generator.Emit;

/// <summary>
/// The restart rule of the development loop (plan section 4, "Hot Reload signal"): a contract edit restarts the app and
/// is never patched into it. A patched contract would change the wire without the page's generated client changing,
/// and the catalog's static data (the fingerprint, the commands, their limits, the page security) would keep its old
/// values, since Hot Reload never runs a static initializer again.
/// <para>
/// In a Development build the generator adds one enum whose only member is named from a hash of everything it
/// generated for the contracts (<c>Spar.Contracts.g.cs</c>: the catalog, the dispatch and the serializers). An edit that
/// changes any of that, such as a command's signature, a DTO's or an error case's properties, a wire name or the page
/// security, renames the member; Hot Reload cannot change an existing enum's members, so the edit is a rude edit and
/// <c>dotnet watch</c> (and an IDE) restarts the app with a fresh build, which regenerates the TypeScript client. An edit
/// that leaves the generated code as it was, such as a command's body, keeps the member, and Hot Reload applies it.
/// Other variants have no such enum: Production is never hot reloaded, and the Test variant runs inside tests.
/// </para>
/// </summary>
internal static class ShapeEmitter
{
    /// <summary>The enum's name, which Spar's runtime never reads: only its member's name matters, to the compiler.</summary>
    public const string TypeName = "SparContractShape";

    public static string Emit(string contractsSource)
    {
        return new CodeWriter()
            .Line("// <auto-generated/> Spar: the contracts' shape, so that Hot Reload restarts the app for a contract edit.")
            .Line()
            .Open("namespace Spar.Generated")
            .Line("/// <summary>")
            .Line("/// The member's name changes with the generated contract code. Hot Reload cannot rename an enum member, so a")
            .Line("/// contract edit restarts the app instead of being patched into it (Development builds only).")
            .Line("/// </summary>")
            .Open($"internal enum {TypeName}")
            .Line($"Shape_{Hash(contractsSource)},")
            .Close()
            .Close()
            .ToString();
    }

    /// <summary>The first 16 bytes of the source's SHA-256, as 32 lowercase hex digits.</summary>
    public static string Hash(string source)
    {
        using var sha = SHA256.Create();
        var hash = sha.ComputeHash(Encoding.UTF8.GetBytes(source));
        return string.Concat(hash.Take(16).Select(b => b.ToString("x2")));
    }
}
