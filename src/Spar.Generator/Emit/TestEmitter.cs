using System.Linq;

namespace Spar.Generator.Emit;

/// <summary>
/// The Test variant only (decision "Test host mechanics: the generated entry point"): <c>Program</c> becomes public and
/// an <c>ISparEntryPoint</c>, and each contract gets a typed C# test client that writes the same request bytes a page
/// sends and reads the outcome with the app's own serializers.
/// </summary>
internal static class TestEmitter
{
    private const string Runtime = "global::Spar.Runtime";

    public static string EntryPoint(EntryPointModel entry) =>
        new CodeWriter()
            .Line("// <auto-generated/> Spar, Test variant only.")
            .Line("#nullable enable")
            .Open($"public partial class {entry.TypeName} : global::Spar.ISparEntryPoint")
            .Line("static int global::Spar.ISparEntryPoint.Run(string[] args) => SparEntry(null, args);")
            .Line()
            .Line($"[global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.StaticMethod, Name = \"{entry.MethodName}\")]")
            .Line($"private static extern int SparEntry({entry.TypeName}? program, string[] args);")
            .Close()
            .ToString();

    public static void EmitClient(CodeWriter code, ContractModel contract)
    {
        code.Line($"/// <summary>A typed test client for the <c>{contract.WireName}</c> contract, over the app's real dispatch and serializers.</summary>");
        code.Open($"public sealed class {contract.PascalName}Client({Runtime}.ISparInvoker invoker)");
        var first = true;
        foreach (var command in contract.Commands)
        {
            if (!first)
            {
                code.Line();
            }

            first = false;
            EmitMethod(code, contract, command);
        }

        code.Close();
    }

    private static void EmitMethod(CodeWriter code, ContractModel contract, CommandModel command)
    {
        if (command.IsStream)
        {
            EmitStreamMethod(code, contract, command);
            return;
        }

        if (command.IsResource)
        {
            EmitResourceMethod(code, contract, command);
            return;
        }

        var returnType = command.Return switch
        {
            ReturnShape.None => "global::System.Threading.Tasks.Task",
            ReturnShape.Value => $"global::System.Threading.Tasks.Task<{command.Value!.CSharp}>",
            ReturnShape.ResultWithValue => $"global::System.Threading.Tasks.Task<global::Spar.Result<{command.Value!.CSharp}, {command.ErrorCSharp}>>",
            _ => $"global::System.Threading.Tasks.Task<global::Spar.Result<{command.ErrorCSharp}>>",
        };
        var parameters = command.Request is { } request
            ? $"{request.CSharp} request, global::System.Threading.CancellationToken cancellationToken = default"
            : "global::System.Threading.CancellationToken cancellationToken = default";
        var payload = command.Request is { } r
            ? $"{Runtime}.SparJson.Write(request, SparSerializers.Write{r.Key})"
            : "global::System.ReadOnlyMemory<byte>.Empty";

        code.Line($"/// <summary>Calls <c>{contract.WireName}.{command.WireName}</c>; an infrastructure failure throws <c>SparCallFailedException</c>.</summary>");
        code.Open($"public async {returnType} {Naming.Pascal(command.WireName)}Async({parameters})");
        code.Line($"var outcome = await invoker.InvokeAsync(\"{contract.WireName}\", \"{command.WireName}\", {payload}, cancellationToken);");
        code.Open($"if (outcome.Kind == {Runtime}.SparOutcomeKind.Failure)");
        code.Line($"throw new global::Spar.SparCallFailedException(\"{contract.WireName}\", \"{command.WireName}\", outcome.Failure!);");
        code.Close();
        code.Line();
        switch (command.Return)
        {
            case ReturnShape.None:
                break;
            case ReturnShape.Value:
                code.Line($"return {Runtime}.SparJson.Read(outcome.Payload, SparSerializers.Read{command.Value!.Key});");
                break;
            case ReturnShape.ResultWithValue:
                code.Open($"if (outcome.Kind == {Runtime}.SparOutcomeKind.Value)");
                code.Line($"return {Runtime}.SparJson.Read(outcome.Payload, SparSerializers.Read{command.Value!.Key});");
                code.Close();
                code.Line();
                code.Line($"return {Runtime}.SparJson.Read(outcome.Payload, SparSerializers.Read{command.ErrorKey});");
                break;
            case ReturnShape.ResultWithoutValue:
                code.Open($"if (outcome.Kind == {Runtime}.SparOutcomeKind.Value)");
                code.Line("return global::Spar.Result.Success;");
                code.Close();
                code.Line();
                code.Line($"return {Runtime}.SparJson.Read(outcome.Payload, SparSerializers.Read{command.ErrorKey});");
                break;
        }

        code.Close();
    }

    /// <summary>A resource as one load of its address would run it: its blob, or null when it returned none (a 404).</summary>
    private static void EmitResourceMethod(CodeWriter code, ContractModel contract, CommandModel command)
    {
        var parameters = command.Request is { } request
            ? $"{request.CSharp} request, global::System.Threading.CancellationToken cancellationToken = default"
            : "global::System.Threading.CancellationToken cancellationToken = default";
        var payload = command.Request is { } r
            ? $"{Runtime}.SparJson.Write(request, SparSerializers.Write{r.Key})"
            : "global::System.ReadOnlyMemory<byte>.Empty";

        code.Line($"/// <summary>Loads the resource <c>{contract.WireName}.{command.WireName}</c>; an infrastructure failure throws <c>SparCallFailedException</c>.</summary>");
        code.Line($"public global::System.Threading.Tasks.ValueTask<global::Spar.SparBlob?> {Naming.Pascal(command.WireName)}Async({parameters}) =>");
        code.Line($"    invoker.LoadResourceAsync(\"{contract.WireName}\", \"{command.WireName}\", {payload}, cancellationToken);");
    }

    /// <summary>
    /// A stream as an <c>IAsyncEnumerable</c> of its values (of results, when it declares errors), and a subscription as
    /// one of its items, values and status events, through the bridge's own batching, credits and buffer.
    /// </summary>
    private static void EmitStreamMethod(CodeWriter code, ContractModel contract, CommandModel command)
    {
        var value = command.Value!.CSharp;
        var item = command.Subscription is null
            ? command.ErrorCSharp is null ? value : $"global::Spar.Result<{value}, {command.ErrorCSharp}>"
            : command.ErrorCSharp is null ? $"global::Spar.SparSubscriptionItem<{value}>" : $"global::Spar.SparSubscriptionItem<{value}, {command.ErrorCSharp}>";
        var parameters = command.Request is { } request
            ? $"{request.CSharp} request, global::System.Threading.CancellationToken cancellationToken = default"
            : "global::System.Threading.CancellationToken cancellationToken = default";
        var payload = command.Request is { } r
            ? $"{Runtime}.SparJson.Write(request, SparSerializers.Write{r.Key})"
            : "global::System.ReadOnlyMemory<byte>.Empty";
        var readers = command.ErrorKey is null
            ? $"SparSerializers.Read{command.Value.Key}"
            : $"SparSerializers.Read{command.Value.Key}, SparSerializers.Read{command.ErrorKey}";
        var name = $"\"{contract.WireName}\", \"{command.WireName}\"";
        var types = command.ErrorCSharp is null ? value : $"{value}, {command.ErrorCSharp}";
        var open = command.Subscription is { } subscription
            ? $"invoker.Streams.Subscribe<{types}>({name}, {payload}, {readers}, automatic: {(subscription.Automatic ? "true" : "false")}, cancellationToken)"
            : $"invoker.Streams.Stream<{types}>({name}, {payload}, {readers}, cancellationToken)";
        var kind = command.Subscription is null ? "Streams" : "Subscribes to";

        code.Line($"/// <summary>{kind} <c>{contract.WireName}.{command.WireName}</c>; an infrastructure failure throws <c>SparCallFailedException</c>.</summary>");
        code.Line($"public global::System.Collections.Generic.IAsyncEnumerable<{item}> {Naming.Pascal(command.WireName)}Async({parameters}) =>");
        code.Line($"    {open};");
    }

    public static string Clients(System.Collections.Generic.IReadOnlyList<ContractModel> contracts)
    {
        var code = new CodeWriter()
            .Line("// <auto-generated/> Spar, Test variant only: typed test clients.")
            .Line("#nullable enable")
            .Line("using Spar.Generated;")
            .Line();
        foreach (var group in contracts.GroupBy(c => c.Namespace))
        {
            if (group.Key.Length > 0)
            {
                code.Open($"namespace {group.Key}");
            }

            foreach (var contract in group)
            {
                EmitClient(code, contract);
                code.Line();
            }

            if (group.Key.Length > 0)
            {
                code.Close();
            }
        }

        return code.ToString();
    }
}
