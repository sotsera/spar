using System.Collections.Immutable;
using System.Linq;
using Microsoft.CodeAnalysis.CSharp;

namespace Spar.Generator.Emit;

/// <summary>
/// The tested app of a black-box test project, as the build describes it: an <c>AdditionalFiles</c> item for each
/// <c>SparTestedApplication</c>, with its name, app id, executable and project folder as item metadata.
/// </summary>
internal sealed record TestedAppModel(string Name, string AppId, string Executable, string ProjectDirectory);

/// <summary>
/// The <c>Projects</c> class of a test project with <c>&lt;SparBlackBoxTests&gt;true&lt;/SparBlackBoxTests&gt;</c>
/// (decision "M1b's remaining questions without a spike"): one property per tested app, a <c>Spar.Testing.SparProject</c>
/// that the black-box fixture launches, as in <c>SparBlackBox.LaunchAsync(Projects.Notebook)</c>. Internal, in the
/// global namespace, so <c>Projects.X</c> reads the same in every test file.
/// </summary>
internal static class ProjectsEmitter
{
    public static string Emit(ImmutableArray<TestedAppModel> apps)
    {
        var code = new CodeWriter()
            .Line("// <auto-generated/> Spar: the tested apps of this black-box test project.")
            .Line("#nullable enable")
            .Line()
            .Line("/// <summary>The apps this test project names with SparTestedApplication, for SparBlackBox.LaunchAsync.</summary>")
            .Line("[global::System.CodeDom.Compiler.GeneratedCode(\"Spar.Generator\", null)]")
            .Open("internal static class Projects");
        var first = true;
        foreach (var app in apps.OrderBy(app => app.Name, System.StringComparer.Ordinal))
        {
            if (!first)
            {
                code.Line();
            }

            first = false;
            code.Line($"/// <summary>{Xml(app.Name)} ({Xml(app.AppId)}): its Production executable, published beside the tests.</summary>")
                .Line($"public static global::Spar.Testing.SparProject {PropertyName(app.Name)} {{ get; }} = new(")
                .Line($"    {Literal(app.Name)},")
                .Line($"    {Literal(app.AppId)},")
                .Line($"    {Literal(app.Executable)},")
                .Line($"    {Literal(app.ProjectDirectory)});");
        }

        code.Close();
        return code.ToString();
    }

    /// <summary>The app's name as a C# property name: other characters become <c>_</c>, a leading digit gets one, a keyword <c>@</c>.</summary>
    private static string PropertyName(string name)
    {
        var identifier = Naming.Identifier(name);
        if (identifier.Length == 0 || char.IsDigit(identifier[0]))
        {
            identifier = "_" + identifier;
        }

        return SyntaxFacts.GetKeywordKind(identifier) == SyntaxKind.None ? identifier : "@" + identifier;
    }

    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);

    private static string Xml(string value) => value.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
}
